package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strconv"
	"strings"
)

type gen struct {
	sc  *schema
	buf bytes.Buffer

	snap    string // snapshot type
	fz      string // freezer type
	uf      string // unfreezer type
	vd      string // validator type
	gr      string // graph type
	load    string // loader function
	build   string // snapshot construction from parsed sections
	lc      string // lower-case stem for unexported helpers
	maxSecs int    // upper bound on sections emitted by a snapshot
}

func (g *gen) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func generate(sc *schema, cmdline string) ([]byte, error) {
	g := &gen{sc: sc}
	first := sc.roots[0]
	g.snap = sc.prefix + first.name + "Snapshot"
	g.lc = lowerFirst(sc.prefix + first.name)
	g.fz = g.lc + "Freezer"
	g.uf = g.lc + "Unfreezer"
	g.vd = g.lc + "Validator"
	g.gr = g.lc + "Graph"
	g.load = "load" + sc.prefix + first.name + "Snapshot"
	g.build = "build" + sc.prefix + first.name + "Snapshot"
	g.maxSecs = len(sc.tableNodes()) + len(sc.pools) + 2

	g.genFlatTypes()
	g.genSnapshot()
	g.genViews()
	g.genSliceViews()
	g.genMapKeyHelpers()
	g.genMapViews()
	g.genIfaceViews()
	g.genFreezer()
	g.genUnfreezer()
	g.genValidator()
	g.genIO()
	for _, n := range sc.compacts {
		g.genCompact(n)
	}

	used, err := usedPackages(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by cnfgo; DO NOT EDIT.\n// %s\n\npackage %s\n\nimport (\n", cmdline, sc.pkg.Name())
	for _, p := range []string{"cmp", "encoding/binary", "errors", "fmt", "io", "iter", "math", "net/netip", "reflect", "runtime", "slices", "strings", "sync", "time"} {
		if used[p[strings.LastIndex(p, "/")+1:]] {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}
	out.WriteString("\n")
	fmt.Fprintf(&out, "\t%q\n", "github.com/Voskan/cnfgo/cnfrt")
	if used["unsafemmap"] {
		fmt.Fprintf(&out, "\t%q\n", "github.com/Voskan/cnfgo/unsafemmap")
	}
	var others []string
	for path := range sc.imports.byPath {
		if used[sc.imports.byPath[path]] {
			others = append(others, path)
		}
	}
	sort.Strings(others)
	for _, path := range others {
		alias := sc.imports.byPath[path]
		if alias == path[strings.LastIndex(path, "/")+1:] {
			fmt.Fprintf(&out, "\t%q\n", path)
		} else {
			fmt.Fprintf(&out, "\t%s %q\n", alias, path)
		}
	}
	out.WriteString(")\n\n")
	out.Write(g.buf.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("formatting generated code: %v", err)
	}
	return src, nil
}

// usedPackages returns the package names referenced by selector
// expressions in the generated declarations body.
func usedPackages(body []byte) (map[string]bool, error) {
	src := append([]byte("package p\n"), body...)
	f, err := parser.ParseFile(token.NewFileSet(), "gen.go", src, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("parsing generated code: %v", err)
	}
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	return used, nil
}

// --- flat types --------------------------------------------------------------

func (g *gen) genFlatTypes() {
	sc := g.sc
	g.p("// SchemaHash%s identifies the layout of %s images.", sc.prefix+sc.roots[0].name, g.snap)
	g.p("const SchemaHash%s uint64 = %#x", sc.prefix+sc.roots[0].name, sc.hash)
	g.p("")
	for _, fs := range sc.flats {
		g.p("// %s is a pointer-free flat record (%d bytes, identical layout on 32-bit and 64-bit platforms).", fs.name, fs.size)
		g.p("type %s struct {", fs.name)
		for _, f := range fs.fields {
			g.p("\t%s %s // offset %d", f.name, f.expr, f.off)
		}
		g.p("}")
		g.p("")
	}
	g.p("func init() {")
	g.p("\tfor _, c := range []struct {")
	g.p("\t\tt    reflect.Type")
	g.p("\t\tsize uintptr")
	g.p("\t}{")
	for _, fs := range sc.flats {
		g.p("\t\t{reflect.TypeFor[%s](), %d},", fs.name, fs.size)
	}
	g.p("\t} {")
	g.p("\t\tif c.t.Size() != c.size {")
	g.p("\t\t\tpanic(fmt.Sprintf(\"cnfgo: %%v has size %%d, generated for %%d\", c.t, c.t.Size(), c.size))")
	g.p("\t\t}")
	g.p("\t\tif err := cnfrt.CheckNoPointers(c.t); err != nil {")
	g.p("\t\t\tpanic(err)")
	g.p("\t\t}")
	g.p("\t}")
	g.p("}")
	g.p("")
}

// --- snapshot ----------------------------------------------------------------

func (g *gen) genSnapshot() {
	sc := g.sc
	g.p("// %s is an immutable, pointer-free snapshot of an object graph. Every", g.snap)
	g.p("// node table and pool is a slice of a flat type without Go pointers, so the")
	g.p("// garbage collector never scans its contents.")
	g.p("//")
	g.p("// A snapshot is safe for concurrent use. Snapshots opened from memory-mapped")
	g.p("// files must not be used after Close; string getters on such snapshots")
	g.p("// return copies.")
	g.p("type %s struct {", g.snap)
	for _, n := range sc.tableNodes() {
		g.p("\tnodes%s []%s", n.name, n.flatName)
	}
	for _, n := range sc.compacts {
		g.p("\tinlineRoot%s [1]%s", n.name, n.flatName)
	}
	for _, p := range sc.pools {
		g.p("\t%s []%s // %s", p.field, p.flatExpr, p.key)
	}
	g.p("\tstrBlob    string")
	g.p("\tdict       *cnfrt.Dict")
	g.p("\tdictStrs   []string // chunks of dict, captured when the snapshot was built or loaded")
	g.p("\tlocEntries []cnfrt.LocEntry")
	g.p("\tlocs       []*time.Location")
	g.p("\tzoned      []netip.Addr")
	g.p("\tflags      uint32")
	g.p("\tseed       uint64")
	g.p("\trootTable  uint32")
	g.p("\trootID     uint32")
	g.p("\tcloneStrs  bool")
	g.p("\tisMmap     bool")
	g.p("\tmapping    *unsafemmap.Mapping")
	g.p("\tleak       *cnfrt.LeakHandle")
	g.p("}")
	g.p("")
	s := "s *" + g.snap
	g.p("// str returns the string of span x. Strings of memory-mapped snapshots")
	g.p("// are copied, so that they stay valid after Close.")
	g.p("func (%s) str(x cnfrt.Span32) string {", s)
	g.p("\tr := s.rawStr(x)")
	g.p("\tif s.cloneStrs {")
	g.p("\t\tr = string([]byte(r))")
	g.p("\t\truntime.KeepAlive(s)")
	g.p("\t}")
	g.p("\treturn r")
	g.p("}")
	g.p("")
	g.p("// rawStr returns the string of span x without copying. Dictionary spans")
	g.p("// are resolved in the chunks captured from the snapshot's cnfrt.Dict; a")
	g.p("// nil span (cnfrt.NilSpanOff) has the dictionary bit set and zero length.")
	g.p("func (%s) rawStr(x cnfrt.Span32) string {", s)
	g.p("\tif x.Off < cnfrt.DictSpanBit {")
	g.p("\t\treturn s.strBlob[x.Off:][:x.Len]")
	g.p("\t}")
	g.p("\tif x.Len == 0 {")
	g.p("\t\treturn \"\"")
	g.p("\t}")
	g.p("\treturn s.dictStrs[x.Off>>21&(1<<10-1)][x.Off&(1<<21-1):][:x.Len]")
	g.p("}")
	g.p("")
	for _, n := range sc.tableNodes() {
		g.p("func (%s) view%d(id uint32) %s {", s, n.tbl, n.viewName)
		g.p("\tif id == 0 {")
		g.p("\t\treturn %s{}", n.viewName)
		g.p("\t}")
		g.p("\treturn %s{cnfSnap: s, cnfID: id}", n.viewName)
		g.p("}")
		g.p("")
	}
	for i, ifc := range sc.ifaces {
		g.p("func (%s) iview%d(x cnfrt.VariantTag) %s {", s, i, ifc.viewName)
		g.p("\tif x.Tag == 0 {")
		g.p("\t\treturn %s{}", ifc.viewName)
		g.p("\t}")
		g.p("\treturn %s{cnfSnap: s, cnfTag: x}", ifc.viewName)
		g.p("}")
		g.p("")
	}
	for _, sh := range sc.shapes {
		if sh.kind == kArrayInline && sh.n > 0 && !g.directArray(sh) {
			g.p("func (%s) arr%d(x %s) (out %s) {", s, sh.id, sh.flatExpr, sh.goExpr)
			g.p("\tfor i := range x {")
			g.p("\t\tout[i] = %s", g.scalarRead(sh.elem, "x[i]"))
			g.p("\t}")
			g.p("\treturn out")
			g.p("}")
			g.p("")
		}
		if sh.kind == kStructKey {
			g.p("func (%s) skey%d(x %s) (out %s) {", s, sh.id, sh.flatExpr, sh.goExpr)
			usedX := false
			for _, f := range sh.sfields {
				if f.sh.isZeroArray() {
					continue
				}
				usedX = true
				g.p("\tout.%s = %s", f.name, g.read(f.sh, "x."+f.flatName, "s"))
			}
			if !usedX {
				g.p("\t_ = x")
			}
			g.p("\treturn out")
			g.p("}")
			g.p("")
		}
	}
	for i, r := range sc.roots {
		g.p("// Root%s returns the root view if the snapshot's root is a %s, or the zero view.", r.name, r.name)
		g.p("func (%s) Root%s() %s {", s, r.name, r.viewName)
		g.p("\tif s == nil || s.rootTable != %d {", r.tbl)
		g.p("\t\treturn %s{}", r.viewName)
		g.p("\t}")
		g.p("\treturn s.view%d(s.rootID)", r.tbl)
		g.p("}")
		g.p("")
		g.p("// WithRoot%sFaultSafe calls fn with the %s root view and converts memory", r.name, r.name)
		g.p("// faults (for example from a mapped file truncated by another process) into")
		g.p("// cnfrt.ErrMmapFault.")
		g.p("func (%s) WithRoot%sFaultSafe(fn func(%s) error) error {", s, r.name, r.viewName)
		g.p("\terr := unsafemmap.FaultSafe(func() error { return fn(s.Root%s()) })", r.name)
		g.p("\truntime.KeepAlive(s)")
		g.p("\treturn err")
		g.p("}")
		g.p("")
		if i == 0 {
			g.p("// Root returns the root view of the snapshot.")
			g.p("func (%s) Root() %s { return s.Root%s() }", s, r.viewName, r.name)
			g.p("")
			g.p("// WithRootFaultSafe calls fn with the root view and converts memory faults")
			g.p("// (for example from a mapped file truncated by another process) into")
			g.p("// cnfrt.ErrMmapFault.")
			g.p("func (%s) WithRootFaultSafe(fn func(%s) error) error {", s, r.viewName)
			g.p("\treturn s.WithRoot%sFaultSafe(fn)", r.name)
			g.p("}")
			g.p("")
		}
	}
	for _, n := range sc.tableNodes() {
		g.p("// Len%s returns the number of %s nodes in the snapshot.", n.name, n.name)
		g.p("func (%s) Len%s() int { return len(s.nodes%s) }", s, n.name, n.name)
		g.p("")
	}
	g.p("func (%s) nodeCount() int {", s)
	g.p("\treturn %s", strings.Join(func() []string {
		var parts []string
		for _, n := range sc.tableNodes() {
			parts = append(parts, "len(s.nodes"+n.name+")")
		}
		return parts
	}(), " + "))
	g.p("}")
	g.p("")
	g.p("// IsMmap reports whether the snapshot is backed by a memory-mapped file.")
	g.p("func (%s) IsMmap() bool { return s.isMmap }", s)
	g.p("")
	g.p("// Cyclic reports whether the snapshot was produced by a FreezeCyclic function.")
	g.p("func (%s) Cyclic() bool { return s.flags&cnfrt.FlagCyclicAllowed != 0 }", s)
	g.p("")
	g.p("// UsesDict reports whether the snapshot stores any strings in a shared cnfrt.Dict.")
	g.p("func (%s) UsesDict() bool { return s.flags&cnfrt.FlagHasDict != 0 }", s)
	g.p("")
	g.p("// SizeBytes returns the total size of the snapshot's tables, pools and string blob.")
	g.p("func (%s) SizeBytes() int {", s)
	g.p("\tn := len(s.strBlob)")
	for _, n := range sc.tableNodes() {
		g.p("\tn += cnfrt.SliceSize(s.nodes%s)", n.name)
	}
	for _, p := range sc.pools {
		g.p("\tn += cnfrt.SliceSize(s.%s)", p.field)
	}
	g.p("\treturn n")
	g.p("}")
	g.p("")
	g.p("// MarkRetired tells the leak detector, if enabled, that the snapshot is no")
	g.p("// longer expected to be referenced.")
	g.p("func (%s) MarkRetired() { s.leak.MarkRetired() }", s)
	g.p("")
	g.p("// Close releases the memory mapping of a snapshot opened with Map%sFile. It", sc.prefix+sc.roots[0].name)
	g.p("// is idempotent and a no-op for heap snapshots. Views of a closed snapshot")
	g.p("// panic; Close must not be called concurrently with reads.")
	g.p("func (%s) Close() error {", s)
	g.p("\tm := s.mapping")
	g.p("\tif m == nil {")
	g.p("\t\treturn nil")
	g.p("\t}")
	for _, n := range sc.tableNodes() {
		g.p("\ts.nodes%s = nil", n.name)
	}
	for _, p := range sc.pools {
		g.p("\ts.%s = nil", p.field)
	}
	g.p("\ts.strBlob = \"\"")
	g.p("\treturn m.Close()")
	g.p("}")
	g.p("")
}

// --- readers -------------------------------------------------------------------

func (g *gen) directArray(sh *shape) bool {
	e := sh.elem
	return e.goExpr == e.flatExpr && !e.sc.isBool && !e.sc.isCplx
}

func (g *gen) scalarRead(sh *shape, x string) string {
	info := sh.sc
	var e string
	switch {
	case info.isBool:
		e = "(" + x + " != 0)"
		if sh.goExpr != "bool" {
			e = sh.goExpr + e
		}
		return e
	case info.isCplx:
		e = "complex(" + x + "[0], " + x + "[1])"
		base := "complex64"
		if info.size == 16 {
			base = "complex128"
		}
		if sh.goExpr != base {
			e = sh.goExpr + "(" + e + ")"
		}
		return e
	}
	if sh.goExpr == info.flat {
		return x
	}
	return sh.goExpr + "(" + x + ")"
}

func (g *gen) nodeIndex(n *node, id string) string {
	return fmt.Sprintf("nodes%s[%s-1]", n.name, id)
}

func (g *gen) ifaceIndex(ifc *iface) int {
	for i, x := range g.sc.ifaces {
		if x == ifc {
			return i
		}
	}
	panic("unknown interface")
}

// read returns a single-valued view expression for the flat value x.
func (g *gen) read(sh *shape, x, snap string) string {
	switch sh.kind {
	case kScalar:
		return g.scalarRead(sh, x)
	case kString:
		e := snap + ".str(" + x + ")"
		if sh.goExpr != "string" {
			e = sh.goExpr + "(" + e + ")"
		}
		return e
	case kBytes:
		return snap + ".str(" + x + ")"
	case kTime:
		return "cnfrt.DecodeTime(" + x + ", " + snap + ".locs)"
	case kAddr:
		return "cnfrt.DecodeAddr(" + x + ", " + snap + ".zoned)"
	case kPrefix:
		return "cnfrt.DecodePrefix(" + x + ")"
	case kAddrPort:
		return "cnfrt.DecodeAddrPort(" + x + ", " + snap + ".zoned)"
	case kCodec:
		return sh.viewType + "{Raw: " + snap + ".str(" + x + ")}"
	case kNode:
		if sh.node.inlined {
			return fmt.Sprintf("%s{cnfSnap: %s, cnfVal: %s}", sh.node.viewName, snap, x)
		}
		return fmt.Sprintf("%s.view%d(%s)", snap, sh.node.tbl, x)
	case kPtrNode:
		return fmt.Sprintf("%s.view%d(%s)", snap, sh.node.tbl, x)
	case kIface:
		return fmt.Sprintf("%s.iview%d(%s)", snap, g.ifaceIndex(sh.iface), x)
	case kSlice, kArrayPool:
		if sh.pool == nil {
			panic("cnfgo: internal error: no pool for " + sh.key)
		}
		if sh.isZeroArray() {
			return sh.pool.viewName + "{cnfSnap: " + snap + "}"
		}
		return sh.pool.viewName + "{cnfSnap: " + snap + ", cnfSpan: " + x + "}"
	case kMap:
		return sh.viewType + "{cnfSnap: " + snap + ", cnfSpan: " + x + "}"
	case kArrayInline:
		if sh.n == 0 {
			return sh.goExpr + "{}"
		}
		if g.directArray(sh) {
			return x
		}
		return fmt.Sprintf("%s.arr%d(%s)", snap, sh.id, x)
	case kStructKey:
		return fmt.Sprintf("%s.skey%d(%s)", snap, sh.id, x)
	case kOptional:
		if sh.elem.isZeroArray() {
			return sh.viewType + "{Value: " + sh.elem.goExpr + "{}, Valid: " + x + ".P != 0}"
		}
		return sh.viewType + "{Value: " + g.read(sh.elem, x+".V", snap) + ", Valid: " + x + ".P != 0}"
	}
	panic("read: unhandled shape")
}

// --- node views ----------------------------------------------------------------

func presenceTest(n *node, bit int, r string) string {
	if n.nopt > 64 {
		return fmt.Sprintf("%s.PresentBits[%d]&(1<<%d) != 0", r, bit/64, bit%64)
	}
	return fmt.Sprintf("%s.PresentBits&(1<<%d) != 0", r, bit)
}

func (g *gen) genViews() {
	for _, n := range g.sc.nodes {
		v := n.viewName
		if n.inlined {
			g.p("// %s is a read-only view of an inline %s value.", v, n.name)
			g.p("type %s struct {", v)
			g.p("\tcnfSnap *%s", g.snap)
			g.p("\tcnfVal %s", n.flatName)
			g.p("}")
			g.p("")
			g.p("// IsValid reports whether v refers to a value in a snapshot.")
			g.p("func (v %s) IsValid() bool { return v.cnfSnap != nil }", v)
			g.p("")
			g.p("// Snapshot returns the snapshot that holds the value.")
			g.p("func (v %s) Snapshot() *%s { return v.cnfSnap }", v, g.snap)
			g.p("")
			g.p("// Unfreeze rebuilds the value and everything reachable from it as ordinary")
			g.p("// Go values.")
			g.p("func (v %s) Unfreeze() (*%s, error) {", v, n.goExpr)
			g.p("\tif !v.IsValid() {")
			g.p("\t\treturn nil, nil")
			g.p("\t}")
			g.p("\tu := &%s{s: v.cnfSnap}", g.uf)
			g.p("\tp := new(%s)", n.goExpr)
			g.p("\tu.filli%d(&v.cnfVal, p)", n.inlineID)
			g.p("\truntime.KeepAlive(v.cnfSnap)")
			g.p("\treturn p, u.err")
			g.p("}")
			g.p("")
			for _, f := range n.fields {
				g.genGetter(n, f)
			}
			continue
		}
		g.p("// %s is a read-only view of a %s node. The zero value is the nil view;", v, n.name)
		g.p("// like methods on a nil pointer, its field getters panic.")
		g.p("type %s struct {", v)
		g.p("\tcnfSnap *%s", g.snap)
		g.p("\tcnfID uint32")
		g.p("}")
		g.p("")
		g.p("// IsValid reports whether v refers to a node.")
		g.p("func (v %s) IsValid() bool { return v.cnfID != 0 && v.cnfSnap != nil }", v)
		g.p("")
		g.p("// NodeID returns the node's 1-based ID in its table, or 0 for the nil view.")
		g.p("func (v %s) NodeID() cnfrt.NodeID { return cnfrt.NodeID(v.cnfID) }", v)
		g.p("")
		g.p("// Snapshot returns the snapshot that holds the node.")
		g.p("func (v %s) Snapshot() *%s { return v.cnfSnap }", v, g.snap)
		g.p("")
		g.p("// Unfreeze rebuilds the node and everything reachable from it as ordinary")
		g.p("// Go values. Shared nodes and cycles are preserved.")
		g.p("func (v %s) Unfreeze() (*%s, error) {", v, n.goExpr)
		g.p("\tif !v.IsValid() {")
		g.p("\t\treturn nil, nil")
		g.p("\t}")
		g.p("\tu := &%s{s: v.cnfSnap}", g.uf)
		g.p("\tp := u.pn%d(v.cnfID)", n.tbl)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn p, u.err")
		g.p("}")
		g.p("")
		for _, f := range n.fields {
			g.genGetter(n, f)
		}
	}
}

func (g *gen) genGetter(n *node, f *field) {
	v := n.viewName
	row := "v.cnfSnap." + g.nodeIndex(n, "v.cnfID")
	if n.inlined {
		row = "v.cnfVal"
	}
	x := row + "." + f.flatName
	sh := f.sh
	switch sh.kind {
	case kOptional:
		g.p("// %s returns the %s field and whether it is set (non-nil).", f.getter, f.name)
		g.p("func (v %s) %s() (%s, bool) {", v, f.getter, sh.elem.viewTypeField())
		g.p("\tr := &%s", row)
		g.p("\tif !(%s) {", presenceTest(n, f.optBit, "r"))
		g.p("\t\truntime.KeepAlive(v.cnfSnap)")
		g.p("\t\tvar zero %s", sh.elem.viewTypeField())
		g.p("\t\treturn zero, false")
		g.p("\t}")
		if sh.elem.isZeroArray() {
			g.p("\tval := %s", g.read(sh.elem, "", "v.cnfSnap"))
		} else {
			g.p("\tval := %s", g.read(sh.elem, "r."+f.flatName, "v.cnfSnap"))
		}
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn val, true")
		g.p("}")
		g.p("")
		return
	case kCodec:
		g.p("// %s decodes the %s field.", f.getter, f.name)
		g.p("func (v %s) %s() (%s, error) {", v, f.getter, sh.goExpr)
		g.p("\tvar c %s", sh.codec.adapter)
		g.p("\tval, err := c.Decode(v.cnfSnap.str(%s))", x)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn val, err")
		g.p("}")
		g.p("")
		g.p("// %sRaw returns the encoded %s field.", f.getter, f.name)
		g.p("func (v %s) %sRaw() string { return v.cnfSnap.str(%s) }", v, f.getter, x)
		g.p("")
		return
	}
	g.p("// %s returns the %s field.", f.getter, f.name)
	if sh.isZeroArray() {
		g.p("func (v %s) %s() %s { return %s }", v, f.getter, sh.viewType, g.read(sh, "", "v.cnfSnap"))
	} else if sh.kind == kString || sh.kind == kBytes || sh.kind == kNode || sh.kind == kPtrNode || sh.kind == kIface || sh.kind == kSlice || sh.kind == kArrayPool || sh.kind == kMap {
		g.p("func (v %s) %s() %s { return %s }", v, f.getter, sh.viewType, g.read(sh, x, "v.cnfSnap"))
	} else {
		g.p("func (v %s) %s() %s {", v, f.getter, sh.viewType)
		g.p("\tval := %s", g.read(sh, x, "v.cnfSnap"))
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn val")
		g.p("}")
	}
	g.p("")
	if sh.kind == kString || sh.kind == kBytes {
		raw := "v.cnfSnap.rawStr(" + x + ")"
		if sh.kind == kBytes {
			g.p("// %sIsNil reports whether the %s field is nil.", f.getter, f.name)
			g.p("func (v %s) %sIsNil() bool {", v, f.getter)
			g.p("\tok := %s.Off == cnfrt.NilSpanOff", x)
			g.p("\truntime.KeepAlive(v.cnfSnap)")
			g.p("\treturn ok")
			g.p("}")
			g.p("")
		}
		g.p("// %sEquals reports whether the %s field equals s without allocating.", f.getter, f.name)
		g.p("func (v %s) %sEquals(s string) bool {", v, f.getter)
		g.p("\tok := %s == s", raw)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn ok")
		g.p("}")
		g.p("")
		g.p("// Append%s appends the %s field to dst without an intermediate copy.", exportName(f.getter), f.name)
		g.p("func (v %s) Append%s(dst []byte) []byte {", v, exportName(f.getter))
		g.p("\tout := append(dst, %s...)", raw)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn out")
		g.p("}")
		g.p("")
		g.p("// With%s calls fn with the %s field without copying it. fn must not", exportName(f.getter), f.name)
		g.p("// retain the string beyond the call (it may alias a memory-mapped file).")
		g.p("func (v %s) With%s(fn func(string)) {", v, exportName(f.getter))
		g.p("\tfn(%s)", raw)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("}")
		g.p("")
		g.p("// %sLen returns the length of the %s field.", f.getter, f.name)
		g.p("func (v %s) %sLen() int {", v, f.getter)
		g.p("\tn := int(%s.Len)", x)
		g.p("\truntime.KeepAlive(v.cnfSnap)")
		g.p("\treturn n")
		g.p("}")
		g.p("")
	}
}

