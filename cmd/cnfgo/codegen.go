// --- slice views -----------------------------------------------------------------

func (g *gen) genSliceViews() {
	for _, p := range g.sc.pools {
		if p.viewName == "" {
			continue
		}
		e := p.elem
		vt := e.viewType
		g.p("// %s is a read-only view of a slice of %s. It has no function-valued", p.viewName, e.goExpr)
		g.p("// fields, so ranging over All does not allocate.")
		g.p("type %s struct {", p.viewName)
		g.p("\tcnfSnap *%s", g.snap)
		g.p("\tcnfSpan cnfrt.Span32")
		g.p("}")
		g.p("")
		g.p("// IsNil reports whether the slice is nil.")
		g.p("func (s %s) IsNil() bool { return s.cnfSpan.Off == cnfrt.NilSpanOff }", p.viewName)
		g.p("")
		g.p("// Len returns the number of elements.")
		g.p("func (s %s) Len() int { return int(s.cnfSpan.Len) }", p.viewName)
		g.p("")
		g.p("// At returns element i. It panics if i is out of range.")
		g.p("func (s %s) At(i int) %s {", p.viewName, vt)
		if e.isZeroArray() {
			g.p("\t_ = s.cnfSnap.%s[s.cnfSpan.Off:][:s.cnfSpan.Len][i]", p.field)
			g.p("\tval := %s", g.read(e, "", "s.cnfSnap"))
			g.p("\truntime.KeepAlive(s.cnfSnap)")
			g.p("\treturn val")
		} else if e.kind == kString || e.kind == kBytes || e.kind == kNode || e.kind == kPtrNode || e.kind == kIface || e.kind == kSlice || e.kind == kArrayPool || e.kind == kMap {
			g.p("\treturn %s", g.read(e, "s.cnfSnap."+p.field+"[s.cnfSpan.Off:][:s.cnfSpan.Len][i]", "s.cnfSnap"))
		} else {
			g.p("\tval := %s", g.read(e, "s.cnfSnap."+p.field+"[s.cnfSpan.Off:][:s.cnfSpan.Len][i]", "s.cnfSnap"))
			g.p("\truntime.KeepAlive(s.cnfSnap)")
			g.p("\treturn val")
		}
		g.p("}")
		g.p("")
		g.p("// All returns an iterator over the elements.")
		g.p("func (s %s) All() iter.Seq[%s] {", p.viewName, vt)
		g.p("\treturn func(yield func(%s) bool) {", vt)
		g.p("\t\tif s.cnfSpan.Len == 0 {")
		g.p("\t\t\treturn")
		g.p("\t\t}")
		g.p("\t\telems := s.cnfSnap.%s[int(s.cnfSpan.Off) : int(s.cnfSpan.Off)+int(s.cnfSpan.Len)]", p.field)
		if e.isZeroArray() {
			g.p("\t\tfor range elems {")
			g.p("\t\t\tif !yield(%s) {", g.read(e, "", "s.cnfSnap"))
			g.p("\t\t\t\tbreak")
			g.p("\t\t\t}")
			g.p("\t\t}")
		} else {
			g.p("\t\tfor _, e := range elems {")
			g.p("\t\t\tif !yield(%s) {", g.read(e, "e", "s.cnfSnap"))
			g.p("\t\t\t\tbreak")
			g.p("\t\t\t}")
			g.p("\t\t}")
		}
		g.p("\t\truntime.KeepAlive(s.cnfSnap)")
		g.p("\t}")
		g.p("}")
		g.p("")
		if e.kind == kString {
			g.p("// EqualsAt reports whether element i equals str without allocating.")
			g.p("func (s %s) EqualsAt(i int, str string) bool {", p.viewName)
			g.p("\te := s.cnfSnap.%s[s.cnfSpan.Off:][:s.cnfSpan.Len][i]", p.field)
			g.p("\tok := s.cnfSnap.rawStr(e) == str")
			g.p("\truntime.KeepAlive(s.cnfSnap)")
			g.p("\treturn ok")
			g.p("}")
			g.p("")
		}
		if e.kind == kScalar {
			g.p("// CopyTo appends the elements of s to dst and returns the extended slice.")
			g.p("func (s %s) CopyTo(dst []%s) []%s {", p.viewName, vt, vt)
			g.p("\tif s.cnfSpan.Len == 0 {")
			g.p("\t\treturn dst")
			g.p("\t}")
			g.p("\telems := s.cnfSnap.%s[int(s.cnfSpan.Off) : int(s.cnfSpan.Off)+int(s.cnfSpan.Len)]", p.field)
			if e.goExpr == e.flatExpr && !e.sc.isBool && !e.sc.isCplx {
				g.p("\tdst = append(dst, elems...)")
			} else {
				g.p("\tdst = slices.Grow(dst, len(elems))")
				g.p("\tfor _, e := range elems {")
				g.p("\t\tdst = append(dst, %s)", g.scalarRead(e, "e"))
				g.p("\t}")
			}
			g.p("\truntime.KeepAlive(s.cnfSnap)")
			g.p("\treturn dst")
			g.p("}")
			g.p("")
		}
	}
}

// --- map key helpers ---------------------------------------------------------------

func (g *gen) keyHelper(name string, id int) string {
	return fmt.Sprintf("cnf%s%s%d", g.sc.prefix+g.sc.roots[0].name, name, id)
}

func (g *gen) keyHasFloat(k *shape) bool {
	switch k.kind {
	case kScalar:
		return k.sc.isFloat
	case kArrayInline:
		return k.n > 0 && k.elem.sc.isFloat
	case kStructKey:
		for _, f := range k.sfields {
			if g.keyHasFloat(f.sh) {
				return true
			}
		}
	}
	return false
}

func (g *gen) keyNaNExpr(k *shape, x string) string {
	switch k.kind {
	case kScalar:
		return x + " != " + x
	case kArrayInline:
		if k.n == 0 {
			return "false"
		}
		return fmt.Sprintf("%s(%s)", g.keyHelper("HasNaNKey", k.id), x)
	case kStructKey:
		return fmt.Sprintf("%s(%s)", g.keyHelper("HasNaNKey", k.id), x)
	}
	return "false"
}

func (g *gen) goKeyCompare(k *shape, a, b string) string {
	switch k.kind {
	case kString:
		return "strings.Compare(string(" + a + "), string(" + b + "))"
	case kScalar:
		if k.sc.isBool {
			return "cmp.Compare(cnfrt.B2U8(bool(" + a + ")), cnfrt.B2U8(bool(" + b + ")))"
		}
		return "cmp.Compare(" + a + ", " + b + ")"
	case kAddr:
		return "cnfrt.CompareAddr(" + a + ", " + b + ")"
	case kPrefix:
		return "cnfrt.ComparePrefix(" + a + ", " + b + ")"
	case kAddrPort:
		return "cnfrt.CompareAddrPort(" + a + ", " + b + ")"
	case kArrayInline:
		if k.n == 0 {
			return "0"
		}
		return fmt.Sprintf("%s(%s, %s)", g.keyHelper("CmpGoKey", k.id), a, b)
	case kStructKey:
		return fmt.Sprintf("%s(%s, %s)", g.keyHelper("CmpGoKey", k.id), a, b)
	}
	panic("goKeyCompare: unhandled shape")
}

func (g *gen) keyCompare(k *shape, a, b, snap string) string {
	// a is a flat key, b is a Go key value.
	switch k.kind {
	case kString:
		return "strings.Compare(" + snap + ".rawStr(" + a + "), string(" + b + "))"
	case kScalar:
		if k.sc.isBool {
			return "cmp.Compare(" + a + ", cnfrt.B2U8(bool(" + b + ")))"
		}
		return "cmp.Compare(" + k.goExpr + "(" + a + "), " + b + ")"
	case kAddr:
		return "cnfrt.CompareAddr(cnfrt.DecodeAddr(" + a + ", " + snap + ".zoned), " + b + ")"
	case kPrefix:
		return "cnfrt.ComparePrefix(cnfrt.DecodePrefix(" + a + "), " + b + ")"
	case kAddrPort:
		return "cnfrt.CompareAddrPort(cnfrt.DecodeAddrPort(" + a + ", " + snap + ".zoned), " + b + ")"
	case kArrayInline:
		if k.n == 0 {
			return "0"
		}
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("CmpKey", k.id), snap, a, b)
	case kStructKey:
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("CmpKey", k.id), snap, a, b)
	}
	panic("keyCompare: unhandled shape")
}

func (g *gen) flatKeyCompare(k *shape, a, b, snap string) string {
	switch k.kind {
	case kString:
		return "strings.Compare(" + snap + ".rawStr(" + a + "), " + snap + ".rawStr(" + b + "))"
	case kScalar:
		return "cmp.Compare(" + a + ", " + b + ")"
	case kAddr:
		return "cnfrt.CompareAddr(cnfrt.DecodeAddr(" + a + ", " + snap + ".zoned), cnfrt.DecodeAddr(" + b + ", " + snap + ".zoned))"
	case kPrefix:
		return "cnfrt.ComparePrefix(cnfrt.DecodePrefix(" + a + "), cnfrt.DecodePrefix(" + b + "))"
	case kAddrPort:
		return "cnfrt.CompareAddrPort(cnfrt.DecodeAddrPort(" + a + ", " + snap + ".zoned), cnfrt.DecodeAddrPort(" + b + ", " + snap + ".zoned))"
	case kArrayInline:
		if k.n == 0 {
			return "0"
		}
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("CmpFlatKey", k.id), snap, a, b)
	case kStructKey:
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("CmpFlatKey", k.id), snap, a, b)
	}
	panic("flatKeyCompare: unhandled shape")
}

func (g *gen) keyHash(k *shape, x, seed string) string {
	switch k.kind {
	case kString:
		return "cnfrt.HashString(string(" + x + "), " + seed + ")"
	case kScalar:
		switch {
		case k.sc.isBool:
			return "cnfrt.HashUint64(uint64(cnfrt.B2U8(bool(" + x + "))), " + seed + ")"
		case k.sc.isFloat && k.sc.size == 8:
			return "cnfrt.HashUint64(cnfrt.KeyBits64(float64(" + x + ")), " + seed + ")"
		case k.sc.isFloat:
			return "cnfrt.HashUint64(cnfrt.KeyBits32(float32(" + x + ")), " + seed + ")"
		}
		return "cnfrt.HashUint64(uint64(" + x + "), " + seed + ")"
	case kAddr:
		return "cnfrt.HashAddr(" + x + ", " + seed + ")"
	case kPrefix:
		return "cnfrt.HashPrefix(" + x + ", " + seed + ")"
	case kAddrPort:
		return "cnfrt.HashAddrPort(" + x + ", " + seed + ")"
	case kArrayInline:
		if k.n == 0 {
			return "cnfrt.HashUint64(0, " + seed + ")"
		}
		return fmt.Sprintf("%s(%s, %s)", g.keyHelper("HashGoKey", k.id), x, seed)
	case kStructKey:
		return fmt.Sprintf("%s(%s, %s)", g.keyHelper("HashGoKey", k.id), x, seed)
	}
	panic("keyHash: unhandled shape")
}

// flatKeyHash returns the hash of the flat map key x; it equals keyHash of
// the Go key that x was frozen from.
func (g *gen) flatKeyHash(k *shape, x, seed, snap string) string {
	switch k.kind {
	case kString:
		return "cnfrt.HashString(" + snap + ".rawStr(" + x + "), " + seed + ")"
	case kScalar:
		switch {
		case k.sc.isFloat && k.sc.size == 8:
			return "cnfrt.HashUint64(cnfrt.KeyBits64(float64(" + x + ")), " + seed + ")"
		case k.sc.isFloat:
			return "cnfrt.HashUint64(cnfrt.KeyBits32(float32(" + x + ")), " + seed + ")"
		}
		return "cnfrt.HashUint64(uint64(" + x + "), " + seed + ")"
	case kAddr:
		return "cnfrt.HashAddr(cnfrt.DecodeAddr(" + x + ", " + snap + ".zoned), " + seed + ")"
	case kPrefix:
		return "cnfrt.HashPrefix(cnfrt.DecodePrefix(" + x + "), " + seed + ")"
	case kAddrPort:
		return "cnfrt.HashAddrPort(cnfrt.DecodeAddrPort(" + x + ", " + snap + ".zoned), " + seed + ")"
	case kArrayInline:
		if k.n == 0 {
			return "cnfrt.HashUint64(0, " + seed + ")"
		}
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("HashFlatKey", k.id), snap, x, seed)
	case kStructKey:
		return fmt.Sprintf("%s(%s, %s, %s)", g.keyHelper("HashFlatKey", k.id), snap, x, seed)
	}
	panic("flatKeyHash: unhandled shape")
}

func (g *gen) genMapKeyHelpers() {
	seen := map[*shape]bool{}
	var order []*shape
	var collect func(k *shape)
	collect = func(k *shape) {
		if k == nil || seen[k] {
			return
		}
		seen[k] = true
		if k.kind == kStructKey {
			for _, f := range k.sfields {
				collect(f.sh)
			}
			order = append(order, k)
		} else if k.kind == kArrayInline && k.n > 0 {
			order = append(order, k)
		}
	}
	for _, sh := range g.sc.shapes {
		if sh.kind == kMap {
			collect(sh.mkey)
		}
	}
	for _, k := range order {
		switch k.kind {
		case kArrayInline:
			g.p("func %s(a, b %s) int {", g.keyHelper("CmpGoKey", k.id), k.goExpr)
			g.p("\tfor i := range a {")
			g.p("\t\tif c := %s; c != 0 {", g.goKeyCompare(k.elem, "a[i]", "b[i]"))
			g.p("\t\t\treturn c")
			g.p("\t\t}")
			g.p("\t}")
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, a %s, b %s) int {", g.keyHelper("CmpKey", k.id), g.snap, k.flatExpr, k.goExpr)
			g.p("\t_ = s")
			g.p("\tfor i := range a {")
			g.p("\t\tif c := %s; c != 0 {", g.keyCompare(k.elem, "a[i]", "b[i]", "s"))
			g.p("\t\t\treturn c")
			g.p("\t\t}")
			g.p("\t}")
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, a, b %s) int {", g.keyHelper("CmpFlatKey", k.id), g.snap, k.flatExpr)
			g.p("\t_ = s")
			g.p("\tfor i := range a {")
			g.p("\t\tif c := %s; c != 0 {", g.flatKeyCompare(k.elem, "a[i]", "b[i]", "s"))
			g.p("\t\t\treturn c")
			g.p("\t\t}")
			g.p("\t}")
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(k %s, seed uint64) uint64 {", g.keyHelper("HashGoKey", k.id), k.goExpr)
			g.p("\th := cnfrt.HashUint64(%d, seed)", k.n)
			g.p("\tfor i := range k {")
			g.p("\t\th = cnfrt.HashCombine(h, %s)", g.keyHash(k.elem, "k[i]", "seed"))
			g.p("\t}")
			g.p("\treturn h")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, k %s, seed uint64) uint64 {", g.keyHelper("HashFlatKey", k.id), g.snap, k.flatExpr)
			g.p("\t_ = s")
			g.p("\th := cnfrt.HashUint64(%d, seed)", k.n)
			g.p("\tfor i := range k {")
			g.p("\t\th = cnfrt.HashCombine(h, %s)", g.flatKeyHash(k.elem, "k[i]", "seed", "s"))
			g.p("\t}")
			g.p("\treturn h")
			g.p("}")
			g.p("")
			if k.elem.sc.isFloat {
				g.p("func %s(k %s) bool {", g.keyHelper("HasNaNKey", k.id), k.goExpr)
				g.p("\tfor i := range k {")
				g.p("\t\tif k[i] != k[i] {")
				g.p("\t\t\treturn true")
				g.p("\t\t}")
				g.p("\t}")
				g.p("\treturn false")
				g.p("}")
				g.p("")
			}
		case kStructKey:
			g.p("func %s(a, b %s) int {", g.keyHelper("CmpGoKey", k.id), k.goExpr)
			for _, f := range k.sfields {
				if f.sh.isZeroArray() {
					continue
				}
				g.p("\tif c := %s; c != 0 {", g.goKeyCompare(f.sh, "a."+f.name, "b."+f.name))
				g.p("\t\treturn c")
				g.p("\t}")
			}
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, a %s, b %s) int {", g.keyHelper("CmpKey", k.id), g.snap, k.flatExpr, k.goExpr)
			g.p("\t_ = s")
			for _, f := range k.sfields {
				if f.sh.isZeroArray() {
					continue
				}
				g.p("\tif c := %s; c != 0 {", g.keyCompare(f.sh, "a."+f.flatName, "b."+f.name, "s"))
				g.p("\t\treturn c")
				g.p("\t}")
			}
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, a, b %s) int {", g.keyHelper("CmpFlatKey", k.id), g.snap, k.flatExpr)
			g.p("\t_ = s")
			for _, f := range k.sfields {
				if f.sh.isZeroArray() {
					continue
				}
				g.p("\tif c := %s; c != 0 {", g.flatKeyCompare(f.sh, "a."+f.flatName, "b."+f.flatName, "s"))
				g.p("\t\treturn c")
				g.p("\t}")
			}
			g.p("\treturn 0")
			g.p("}")
			g.p("")
			g.p("func %s(k %s, seed uint64) uint64 {", g.keyHelper("HashGoKey", k.id), k.goExpr)
			g.p("\th := cnfrt.HashUint64(%d, seed)", len(k.sfields))
			for _, f := range k.sfields {
				g.p("\th = cnfrt.HashCombine(h, %s)", g.keyHash(f.sh, "k."+f.name, "seed"))
			}
			g.p("\treturn h")
			g.p("}")
			g.p("")
			g.p("func %s(s *%s, k %s, seed uint64) uint64 {", g.keyHelper("HashFlatKey", k.id), g.snap, k.flatExpr)
			g.p("\t_ = s")
			g.p("\th := cnfrt.HashUint64(%d, seed)", len(k.sfields))
			for _, f := range k.sfields {
				if f.sh.isZeroArray() {
					g.p("\th = cnfrt.HashCombine(h, %s)", g.flatKeyHash(f.sh, "", "seed", "s"))
				} else {
					g.p("\th = cnfrt.HashCombine(h, %s)", g.flatKeyHash(f.sh, "k."+f.flatName, "seed", "s"))
				}
			}
			g.p("\treturn h")
			g.p("}")
			g.p("")
			if g.keyHasFloat(k) {
				g.p("func %s(k %s) bool {", g.keyHelper("HasNaNKey", k.id), k.goExpr)
				for _, f := range k.sfields {
					if g.keyHasFloat(f.sh) {
						g.p("\tif %s {", g.keyNaNExpr(f.sh, "k."+f.name))
						g.p("\t\treturn true")
						g.p("\t}")
					}
				}
				g.p("\treturn false")
				g.p("}")
				g.p("")
			}
		}
	}
}

// --- map views ---------------------------------------------------------------------

func (g *gen) genMapViews() {
	for _, sh := range g.sc.shapes {
		if sh.kind != kMap {
			continue
		}
		k, v := sh.mkey, sh.elem
		mv := sh.viewType
		kvs := "m.cnfSpan"
		spanType := "cnfrt.Span32"
		if sh.hashed {
			kvs = "m.cnfSpan.KV"
			spanType = "cnfrt.HashSpan"
		}
		vview := v.viewType
		g.p("// %s is a read-only view of a %s.", mv, sh.goExpr)
		g.p("type %s struct {", mv)
		g.p("\tcnfSnap *%s", g.snap)
		g.p("\tcnfSpan %s", spanType)
		g.p("}")
		g.p("")
		g.p("// IsNil reports whether the map is nil.")
		g.p("func (m %s) IsNil() bool { return %s.Off == cnfrt.NilSpanOff }", mv, kvs)
		g.p("")
		g.p("// Len returns the number of entries.")
		g.p("func (m %s) Len() int { return int(%s.Len) }", mv, kvs)
		g.p("")
		g.p("func (m %s) cnfEntries() []%s {", mv, sh.kv.name)
		g.p("\tif %s.Len == 0 {", kvs)
		g.p("\t\treturn nil")
		g.p("\t}")
		g.p("\toff := int(%s.Off)", kvs)
		g.p("\treturn m.cnfSnap.%s[off : off+int(%s.Len)]", sh.pool.field, kvs)
		g.p("}")
		g.p("")
		g.p("// Get returns the value stored for k.")
		g.p("func (m %s) Get(k %s) (%s, bool) {", mv, k.goExpr, vview)
		g.p("\tkv := m.cnfEntries()")
		if g.keyHasFloat(k) {
			g.p("\tif %s {", g.keyNaNExpr(k, "k"))
			g.p("\t\truntime.KeepAlive(m.cnfSnap)")
			g.p("\t\tvar zero %s", vview)
			g.p("\t\treturn zero, false")
			g.p("\t}")
		}
		if sh.hashed {
			g.p("\tif len(kv) > 0 {")
			g.p("\t\tidx := m.cnfSnap.%s[int(m.cnfSpan.Idx.Off) : int(m.cnfSpan.Idx.Off)+int(m.cnfSpan.Idx.Len)]", sh.idxPool.field)
			g.p("\t\tmask := uint64(len(idx) - 1)")
			g.p("\t\th := %s", g.keyHash(k, "k", "m.cnfSnap.seed"))
			g.p("\t\tfor probe := range uint64(len(idx)) {")
			g.p("\t\t\tslot := idx[(h+probe)&mask]")
			g.p("\t\t\tif slot == 0 || int(slot) > len(kv) {")
			g.p("\t\t\t\tbreak")
			g.p("\t\t\t}")
			if k.isZeroArray() && v.isZeroArray() {
				g.p("\t\t\tval := %s", g.read(v, "", "m.cnfSnap"))
				g.p("\t\t\truntime.KeepAlive(m.cnfSnap)")
				g.p("\t\t\treturn val, true")
			} else {
				g.p("\t\t\tif e := &kv[slot-1]; %s == 0 {", g.keyCompare(k, "e.K", "k", "m.cnfSnap"))
				g.p("\t\t\t\tval := %s", g.read(v, "e.V", "m.cnfSnap"))
				g.p("\t\t\t\truntime.KeepAlive(m.cnfSnap)")
				g.p("\t\t\t\treturn val, true")
				g.p("\t\t\t}")
			}
			g.p("\t\t}")
			g.p("\t}")
		} else {
			g.p("\tlo, hi := 0, len(kv)")
			g.p("\tfor lo < hi {")
			g.p("\t\tmid := int(uint(lo+hi) >> 1)")
			g.p("\t\tswitch c := %s; {", g.keyCompare(k, "kv[mid].K", "k", "m.cnfSnap"))
			g.p("\t\tcase c < 0:")
			g.p("\t\t\tlo = mid + 1")
			g.p("\t\tcase c > 0:")
			g.p("\t\t\thi = mid")
			g.p("\t\tdefault:")
			g.p("\t\t\tval := %s", g.read(v, "kv[mid].V", "m.cnfSnap"))
			g.p("\t\t\truntime.KeepAlive(m.cnfSnap)")
			g.p("\t\t\treturn val, true")
			g.p("\t\t}")
			g.p("\t}")
		}
		g.p("\truntime.KeepAlive(m.cnfSnap)")
		g.p("\tvar zero %s", vview)
		g.p("\treturn zero, false")
		g.p("}")
		g.p("")
		g.p("// All returns an iterator over the entries in ascending key order.")
		g.p("func (m %s) All() iter.Seq2[%s, %s] {", mv, k.goExpr, vview)
		g.p("\treturn func(yield func(%s, %s) bool) {", k.goExpr, vview)
		g.p("\t\tkv := m.cnfEntries()")
		g.p("\t\tif len(kv) == 0 {")
		g.p("\t\t\treturn")
		g.p("\t\t}")
		g.p("\t\tfor i := range kv {")
		if k.isZeroArray() && v.isZeroArray() {
			g.p("\t\t\t_ = i")
			g.p("\t\t\tif !yield(%s, %s) {", g.read(k, "", "m.cnfSnap"), g.read(v, "", "m.cnfSnap"))
		} else {
			g.p("\t\t\te := &kv[i]")
			g.p("\t\t\tif !yield(%s, %s) {", g.read(k, "e.K", "m.cnfSnap"), g.read(v, "e.V", "m.cnfSnap"))
		}
		g.p("\t\t\t\tbreak")
		g.p("\t\t\t}")
		g.p("\t\t}")
		g.p("\t\truntime.KeepAlive(m.cnfSnap)")
		g.p("\t}")
		g.p("}")
		g.p("")
		g.p("// Keys returns an iterator over the keys in ascending order.")
		g.p("func (m %s) Keys() iter.Seq[%s] {", mv, k.goExpr)
		g.p("\treturn func(yield func(%s) bool) {", k.goExpr)
		g.p("\t\tkv := m.cnfEntries()")
		g.p("\t\tif len(kv) == 0 {")
		g.p("\t\t\treturn")
		g.p("\t\t}")
		if k.isZeroArray() {
			g.p("\t\tfor range kv {")
			g.p("\t\t\tif !yield(%s) {", g.read(k, "", "m.cnfSnap"))
		} else {
			g.p("\t\tfor _, e := range kv {")
			g.p("\t\t\tif !yield(%s) {", g.read(k, "e.K", "m.cnfSnap"))
		}
		g.p("\t\t\t\tbreak")
		g.p("\t\t\t}")
		g.p("\t\t}")
		g.p("\t\truntime.KeepAlive(m.cnfSnap)")
		g.p("\t}")
		g.p("}")
		g.p("")
	}
}

// --- interface views -----------------------------------------------------------------

func (g *gen) implMethod(ifc *iface, im ifaceImpl) string {
	name := "As" + im.node.name
	if im.ptr {
		for _, o := range ifc.impls {
			if o.node == im.node && !o.ptr {
				return name + "Ptr"
			}
		}
	}
	return name
}

func (g *gen) genIfaceViews() {
	for _, ifc := range g.sc.ifaces {
		v := ifc.viewName
		g.p("// %s is a read-only view of a %s interface value.", v, ifc.name)
		g.p("type %s struct {", v)
		g.p("\tcnfSnap *%s", g.snap)
		g.p("\tcnfTag cnfrt.VariantTag")
		g.p("}")
		g.p("")
		g.p("// IsNil reports whether the interface value is nil.")
		g.p("func (v %s) IsNil() bool { return v.cnfTag.Tag == 0 }", v)
		g.p("")
		g.p("// Tag returns the 1-based index of the dynamic type in the implementation")
		g.p("// list, or 0 for nil.")
		g.p("func (v %s) Tag() int { return int(v.cnfTag.Tag) }", v)
		g.p("")
		for t, im := range ifc.impls {
			g.p("// %s returns the value if its dynamic type is %s.", g.implMethod(ifc, im), im.expr)
			g.p("func (v %s) %s() (%s, bool) {", v, g.implMethod(ifc, im), im.node.viewName)
			g.p("\tif v.cnfTag.Tag != %d {", t+1)
			g.p("\t\treturn %s{}, false", im.node.viewName)
			g.p("\t}")
			g.p("\treturn v.cnfSnap.view%d(v.cnfTag.ID), true", im.node.tbl)
			g.p("}")
			g.p("")
		}
	}
}

// --- freezer ---------------------------------------------------------------------------

func (g *gen) nodeNeedsMeasure(n *node) bool {
	if !n.inlined {
		return true
	}
	for _, fl := range n.fields {
		if g.needsMeasure(fl.sh) {
			return true
		}
	}
	return false
}

func (g *gen) needsMeasure(sh *shape) bool {
	switch sh.kind {
	case kString, kBytes, kCodec, kPtrNode, kSlice, kMap, kIface:
		return true
	case kArrayPool:
		return sh.n > 0
	case kNode:
		return g.nodeNeedsMeasure(sh.node)
	case kOptional:
		return g.needsMeasure(sh.elem)
	case kStructKey:
		for _, f := range sh.sfields {
			if g.needsMeasure(f.sh) {
				return true
			}
		}
	}
	return false
}

// measure returns a statement measuring the addressable Go value src.
func (g *gen) measure(sh *shape, src string) string {
	switch sh.kind {
	case kString:
		return "f.b.MeasureString(string(" + src + "))"
	case kBytes:
		return "f.b.MeasureBytes([]byte(" + src + "))"
	case kCodec:
		return fmt.Sprintf("f.mcodec%d(%s)", sh.id, src)
	case kNode:
		if sh.node.inlined {
			if !g.nodeNeedsMeasure(sh.node) {
				return ""
			}
			return fmt.Sprintf("f.mi%d(&%s)", sh.node.inlineID, src)
		}
		return fmt.Sprintf("f.mv%d(&%s)", sh.node.tbl, src)
	case kPtrNode:
		return fmt.Sprintf("f.mn%d(%s)", sh.node.tbl, src)
	case kArrayPool:
		if sh.n == 0 {
			return ""
		}
		return fmt.Sprintf("f.m%d(%s)", sh.id, src)
	case kSlice, kMap, kIface, kStructKey:
		return fmt.Sprintf("f.m%d(%s)", sh.id, src)
	case kOptional:
		if !g.needsMeasure(sh.elem) {
			return ""
		}
		return "if " + src + " != nil { " + g.measure(sh.elem, "(*"+src+")") + " }"
	}
	return ""
}

// emit returns an expression producing the flat value of the addressable Go
// value src (not valid for kOptional).
func (g *gen) emit(sh *shape, src string) string {
	switch sh.kind {
	case kScalar:
		info := sh.sc
		switch {
		case info.isBool:
			return "cnfrt.B2U8(bool(" + src + "))"
		case info.isCplx:
			return info.flat + "{real(" + src + "), imag(" + src + ")}"
		}
		return info.flat + "(" + src + ")"
	case kString:
		return "f.b.String(string(" + src + "))"
	case kBytes:
		return "f.b.Bytes([]byte(" + src + "))"
	case kTime:
		return "f.b.Time(" + src + ")"
	case kAddr:
		return "f.b.Zones.EncodeAddr(" + src + ")"
	case kPrefix:
		return "cnfrt.EncodePrefix(" + src + ")"
	case kAddrPort:
		return "f.b.Zones.EncodeAddrPort(" + src + ")"
	case kCodec:
		return fmt.Sprintf("f.codec%d(%s)", sh.id, src)
	case kNode:
		if sh.node.inlined {
			return fmt.Sprintf("f.ei%d(&%s)", sh.node.inlineID, src)
		}
		return fmt.Sprintf("f.ev%d(&%s)", sh.node.tbl, src)
	case kPtrNode:
		return fmt.Sprintf("f.en%d(%s)", sh.node.tbl, src)
	case kArrayInline:
		if g.directArray(sh) && sh.goExpr == sh.flatExpr {
			return src
		}
		return fmt.Sprintf("f.e%d(%s)", sh.id, src)
	}
	return fmt.Sprintf("f.e%d(%s)", sh.id, src)
}

// emitPoolElem returns statements storing the Go value src into the pool
// element lvalue dst.
func (g *gen) emitPoolElem(sh *shape, src, dst string) string {
	if sh.kind == kOptional {
		if sh.elem.isZeroArray() {
			return fmt.Sprintf("if %s != nil { %s = %s{P: 1} }", src, dst, sh.opt.name)
		}
		return fmt.Sprintf("if %s != nil { %s = %s{V: %s, P: 1} }", src, dst, sh.opt.name, g.emit(sh.elem, "(*"+src+")"))
	}
	if sh.isZeroArray() {
		return dst + " = [1]byte{}"
	}
	return dst + " = " + g.emit(sh, src)
}

func (g *gen) sortKeys(k *shape, keys string) string {
	switch k.kind {
	case kString:
		return "slices.Sort(" + keys + ")"
	case kScalar:
		if k.sc.isBool {
			return "slices.SortFunc(" + keys + ", func(a, b " + k.goExpr + ") int { return cmp.Compare(cnfrt.B2U8(bool(a)), cnfrt.B2U8(bool(b))) })"
		}
		return "slices.Sort(" + keys + ")"
	case kAddr:
		return "slices.SortFunc(" + keys + ", cnfrt.CompareAddr)"
	case kPrefix:
		return "slices.SortFunc(" + keys + ", cnfrt.ComparePrefix)"
	case kAddrPort:
		return "slices.SortFunc(" + keys + ", cnfrt.CompareAddrPort)"
	case kArrayInline:
		if k.n == 0 {
			return "_ = " + keys
		}
		return fmt.Sprintf("slices.SortFunc(%s, %s)", keys, g.keyHelper("CmpGoKey", k.id))
	case kStructKey:
		return fmt.Sprintf("slices.SortFunc(%s, %s)", keys, g.keyHelper("CmpGoKey", k.id))
	}
	panic("sortKeys: unhandled shape")
}

func (g *gen) mapCachesKeys(sh *shape) bool {
	return sh.kind == kMap && (g.needsMeasure(sh.mkey) || g.needsMeasure(sh.elem))
}

func (g *gen) genFreezer() {
	sc := g.sc
	g.p("type %s struct {", g.fz)
	g.p("\tb   cnfrt.Builder")
	g.p("\ts   *%s", g.snap)
	g.p("\ttmp []byte")
	g.p("\t// Pack functions freeze into spare, whose tables and pools are reused")
	g.p("\t// across calls, and reuse strBuf for the string blob.")
	g.p("\tscratch bool")
	g.p("\tspare   *%s", g.snap)
	g.p("\tstrBuf  []byte")
	for _, p := range sc.pools {
		g.p("\tc%d, p%d uint32 // %s", p.idx, p.idx, p.key)
	}
	for _, sh := range sc.shapes {
		if sh.kind == kMap {
			g.p("\tk%d []%s // reusable key buffer of %s", sh.id, sh.mkey.goExpr, sh.goExpr)
			if g.mapCachesKeys(sh) {
				g.p("\tcached%d    [][]%s", sh.id, sh.mkey.goExpr)
				g.p("\tcachedPos%d int", sh.id)
			}
		}
	}
	g.p("}")
	g.p("")
	g.p("var %sPool = sync.Pool{New: func() any { return new(%s) }}", g.fz, g.fz)
	g.p("")
	g.p("// %sMaxScratch bounds the scratch memory a pooled freezer retains.", g.fz)
	g.p("const %sMaxScratch = 64 << 10", g.fz)
	g.p("")
	g.p("func (f *%s) reset() {", g.fz)
	g.p("\tf.b.Reset()")
	g.p("\tf.s = nil")
	g.p("\tf.scratch = false")
	g.p("\tif sp := f.spare; sp != nil {")
	sizes := []string{}
	keep := []string{}
	for _, n := range sc.tableNodes() {
		sizes = append(sizes, "cnfrt.CapBytes(sp.nodes"+n.name+")")
		keep = append(keep, "nodes"+n.name+": sp.nodes"+n.name+"[:0]")
	}
	for _, p := range sc.pools {
		sizes = append(sizes, "cnfrt.CapBytes(sp."+p.field+")")
		keep = append(keep, p.field+": sp."+p.field+"[:0]")
	}
	g.p("\t\tif %s > %sMaxScratch {", strings.Join(sizes, "+"), g.fz)
	g.p("\t\t\tf.spare = nil")
	g.p("\t\t} else {")
	g.p("\t\t\t*sp = %s{%s}", g.snap, strings.Join(keep, ", "))
	g.p("\t\t}")
	g.p("\t}")
	g.p("\tif cap(f.strBuf) > %sMaxScratch {", g.fz)
	g.p("\t\tf.strBuf = nil")
	g.p("\t}")
	g.p("\tif cap(f.tmp) > 4096 {")
	g.p("\t\tf.tmp = nil")
	g.p("\t} else {")
	g.p("\t\tf.tmp = f.tmp[:0]")
	g.p("\t}")
	for _, p := range sc.pools {
		g.p("\tf.c%d, f.p%d = 0, 0", p.idx, p.idx)
	}
	for _, sh := range sc.shapes {
		if sh.kind == kMap {
			g.p("\tif cap(f.k%d) > 256 {", sh.id)
			g.p("\t\tf.k%d = nil", sh.id)
			g.p("\t} else {")
			g.p("\t\tclear(f.k%d[:cap(f.k%d)])", sh.id, sh.id)
			g.p("\t\tf.k%d = f.k%d[:0]", sh.id, sh.id)
			g.p("\t}")
			if g.mapCachesKeys(sh) {
				g.p("\tf.cached%d = nil", sh.id)
				g.p("\tf.cachedPos%d = 0", sh.id)
			}
		}
	}
	g.p("}")
	g.p("")
	g.p("func (f *%s) reserve(next *uint32, limit uint32, n int) uint32 {", g.fz)
	g.p("\toff := *next")
	g.p("\tif uint64(off)+uint64(n) > uint64(limit) {")
	g.p("\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
	g.p("\t}")
	g.p("\t*next += uint32(n)")
	g.p("\treturn off")
	g.p("}")
	g.p("")
	// allocation of exact tables and pools after pass 1
	g.p("func (f *%s) allocate() {", g.fz)
	g.p("\tif f.scratch {")
	g.p("\t\tsp := f.spare")
	g.p("\t\tif sp == nil {")
	g.p("\t\t\tsp = new(%s)", g.snap)
	g.p("\t\t\tf.spare = sp")
	g.p("\t\t}")
	g.p("\t\t*sp = %s{", g.snap)
	for _, n := range sc.tableNodes() {
		g.p("\t\t\tnodes%s: cnfrt.ReuseSlice(sp.nodes%s, f.b.Count(%d)),", n.name, n.name, n.tbl)
	}
	for _, p := range sc.pools {
		g.p("\t\t\t%s: cnfrt.ReuseSlice(sp.%s, int(f.c%d)),", p.field, p.field, p.idx)
	}
	g.p("\t\t}")
	g.p("\t\tf.s = sp")
	g.p("\t} else {")
	g.p("\t\tf.s = &%s{", g.snap)
	for _, n := range sc.tableNodes() {
		g.p("\t\t\tnodes%s: make([]%s, f.b.Count(%d)),", n.name, n.flatName, n.tbl)
	}
	for _, p := range sc.pools {
		g.p("\t\t\t%s: make([]%s, f.c%d),", p.field, p.flatExpr, p.idx)
	}
	g.p("\t\t}")
	g.p("\t}")
	g.p("\tf.b.BeginEmit()")
	g.p("}")
	g.p("")
	g.p("func (f *%s) finish() {", g.fz)
	for _, p := range sc.pools {
		g.p("\tif f.p%d != f.c%d {", p.idx, p.idx)
		g.p("\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
		g.p("\t}")
	}
	for _, n := range sc.tableNodes() {
		g.p("\tif f.b.Assigned(%d) != f.b.Count(%d) {", n.tbl, n.tbl)
		g.p("\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
		g.p("\t}")
	}
	for _, sh := range sc.shapes {
		if g.mapCachesKeys(sh) {
			g.p("\tf.cached%d = nil", sh.id)
		}
	}
	g.p("\ts := f.s")
	g.p("\ts.strBlob = f.b.StrBlob()")
	g.p("\ts.locEntries = f.b.Locs.Entries")
	g.p("\ts.locs = f.b.Locs.Locations()")
	g.p("\ts.zoned = f.b.Zones.Addrs")
	g.p("\ts.seed = f.b.Seed")
	g.p("\tif f.b.UsedDict() {")
	g.p("\t\tif f.b.Opts.Dict.Closed() {")
	g.p("\t\t\tcnfrt.Fail(cnfrt.ErrUnknownDict)")
	g.p("\t\t}")
	g.p("\t\ts.dict = f.b.Opts.Dict")
	g.p("\t\ts.dictStrs = s.dict.Chunks()")
	g.p("\t\ts.flags |= cnfrt.FlagHasDict")
	g.p("\t}")
	g.p("\tif f.b.Mode == cnfrt.ModeCyclic {")
	g.p("\t\ts.flags |= cnfrt.FlagCyclicAllowed")
	g.p("\t}")
	g.p("\tif f.b.Opts.ExactStringDedup {")
	g.p("\t\ts.flags |= cnfrt.FlagFullStringIntern")
	g.p("\t}")
	g.p("}")
	g.p("")
	for _, n := range sc.nodes {
		g.genNodeFreeze(n)
	}
	for _, sh := range sc.shapes {
		g.genShapeFreeze(sh)
	}
	g.p("// track%s registers a snapshot that owns its string blob (a frozen", g.snap)
	g.p("// snapshot or one loaded from a private copy) with the leak detector.")
	g.p("func track%s(s *%s, err error) (*%s, error) {", g.snap, g.snap, g.snap)
	g.p("\tif err != nil {")
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\ts.leak = cnfrt.TrackSnapshot(cnfrt.GlobalLeakDetector(), s, %q, s.strBlob, true)", g.snap)
	g.p("\treturn s, nil")
	g.p("}")
	g.p("")
	g.p("// trackShared%s registers a snapshot whose string blob aliases memory it", g.snap)
	g.p("// does not own (a mapping or a caller's buffer); only the snapshot itself")
	g.p("// is watched.")
	g.p("func trackShared%s(s *%s, err error) (*%s, error) {", g.snap, g.snap, g.snap)
	g.p("\tif err != nil {")
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\ts.leak = cnfrt.TrackSnapshot(cnfrt.GlobalLeakDetector(), s, %q, s.strBlob, false)", g.snap)
	g.p("\treturn s, nil")
	g.p("}")
	g.p("")
	for _, r := range sc.roots {
		g.genFreezeEntry(r)
	}
}

func (g *gen) genNodeFreeze(n *node) {
	if n.inlined {
		id := n.inlineID
		if g.nodeNeedsMeasure(n) {
			g.p("func (f *%s) mi%d(p *%s) {", g.fz, id, n.goExpr)
			for _, fl := range n.fields {
				if s := g.measure(fl.sh, "p."+fl.name); s != "" {
					g.p("\t%s", s)
				}
			}
			g.p("}")
			g.p("")
		}
		g.p("func (f *%s) ei%d(p *%s) (r %s) {", g.fz, id, n.goExpr, n.flatName)
		for _, fl := range n.fields {
			if fl.sh.kind == kOptional {
				g.p("\tif p.%s != nil {", fl.name)
				if n.nopt > 64 {
					g.p("\t\tr.PresentBits[%d] |= 1 << %d", fl.optBit/64, fl.optBit%64)
				} else {
					g.p("\t\tr.PresentBits |= 1 << %d", fl.optBit)
				}
				if !fl.sh.elem.isZeroArray() {
					g.p("\t\tr.%s = %s", fl.flatName, g.emit(fl.sh.elem, "(*p."+fl.name+")"))
				}
				g.p("\t}")
				continue
			}
			if fl.sh.isZeroArray() {
				continue
			}
			g.p("\tr.%s = %s", fl.flatName, g.emit(fl.sh, "p."+fl.name))
		}
		g.p("\treturn r")
		g.p("}")
		g.p("")
		return
	}
	t := n.tbl
	g.p("func (f *%s) mrow%d(p *%s) {", g.fz, t, n.goExpr)
	for _, fl := range n.fields {
		if s := g.measure(fl.sh, "p."+fl.name); s != "" {
			g.p("\t%s", s)
		}
	}
	g.p("}")
	g.p("")
	g.p("func (f *%s) mn%d(p *%s) {", g.fz, t, n.goExpr)
	g.p("\tif p == nil {")
	g.p("\t\treturn")
	g.p("\t}")
	g.p("\tif f.b.Mode == cnfrt.ModeTree {")
	g.p("\t\tf.b.MeasureEnterValue()")
	g.p("\t\tf.mrow%d(p)", t)
	g.p("\t\tf.b.MeasureLeaveValue(%d)", t)
	g.p("\t\treturn")
	g.p("\t}")
	g.p("\taddr := cnfrt.Addr(p)")
	g.p("\tif !f.b.MeasureEnter(addr, %d) {", t)
	g.p("\t\treturn")
	g.p("\t}")
	g.p("\tf.mrow%d(p)", t)
	g.p("\tf.b.MeasureLeave(addr, %d)", t)
	g.p("}")
	g.p("")
	g.p("func (f *%s) mv%d(p *%s) {", g.fz, t, n.goExpr)
	g.p("\tf.b.MeasureEnterValue()")
	g.p("\tf.mrow%d(p)", t)
	g.p("\tf.b.MeasureLeaveValue(%d)", t)
	g.p("}")
	g.p("")
	g.p("func (f *%s) row%d(p *%s) (r %s) {", g.fz, t, n.goExpr, n.flatName)
	for _, fl := range n.fields {
		if fl.sh.kind == kOptional {
			g.p("\tif p.%s != nil {", fl.name)
			if n.nopt > 64 {
				g.p("\t\tr.PresentBits[%d] |= 1 << %d", fl.optBit/64, fl.optBit%64)
			} else {
				g.p("\t\tr.PresentBits |= 1 << %d", fl.optBit)
			}
			if !fl.sh.elem.isZeroArray() {
				g.p("\t\tr.%s = %s", fl.flatName, g.emit(fl.sh.elem, "(*p."+fl.name+")"))
			}
			g.p("\t}")
			continue
		}
		if fl.sh.isZeroArray() {
			continue
		}
		g.p("\tr.%s = %s", fl.flatName, g.emit(fl.sh, "p."+fl.name))
	}
	g.p("\treturn r")
	g.p("}")
	g.p("")
	g.p("func (f *%s) en%d(p *%s) uint32 {", g.fz, t, n.goExpr)
	g.p("\tif p == nil {")
	g.p("\t\treturn 0")
	g.p("\t}")
	g.p("\tif f.b.Mode == cnfrt.ModeTree {")
	g.p("\t\tr := f.row%d(p)", t)
	g.p("\t\tid := f.b.PostID(%d)", t)
	g.p("\t\tf.s.%s = r", g.nodeIndex(n, "id"))
	g.p("\t\treturn id")
	g.p("\t}")
	g.p("\taddr := cnfrt.Addr(p)")
	g.p("\tif id := f.b.Lookup(addr, %d); id != 0 {", t)
	g.p("\t\treturn id")
	g.p("\t}")
	g.p("\tvar id uint32")
	g.p("\tif f.b.Preorder() {")
	g.p("\t\tid = f.b.PreID(%d)", t)
	g.p("\t\tf.b.Record(addr, %d, id)", t)
	g.p("\t}")
	g.p("\tr := f.row%d(p)", t)
	g.p("\tif !f.b.Preorder() {")
	g.p("\t\tid = f.b.PostID(%d)", t)
	g.p("\t\tf.b.Record(addr, %d, id)", t)
	g.p("\t}")
	g.p("\tf.s.%s = r", g.nodeIndex(n, "id"))
	g.p("\treturn id")
	g.p("}")
	g.p("")
	g.p("func (f *%s) ev%d(p *%s) uint32 {", g.fz, t, n.goExpr)
	g.p("\tvar id uint32")
	g.p("\tif f.b.Preorder() {")
	g.p("\t\tid = f.b.PreID(%d)", t)
	g.p("\t}")
	g.p("\tr := f.row%d(p)", t)
	g.p("\tif !f.b.Preorder() {")
	g.p("\t\tid = f.b.PostID(%d)", t)
	g.p("\t}")
	g.p("\tf.s.%s = r", g.nodeIndex(n, "id"))
	g.p("\treturn id")
	g.p("}")
	g.p("")
}

func (g *gen) genShapeFreeze(sh *shape) {
	switch sh.kind {
	case kCodec:
		g.p("func (f *%s) mcodec%d(x %s) {", g.fz, sh.id, sh.goExpr)
		g.p("\tvar c %s", sh.codec.adapter)
		g.p("\tf.tmp = c.Append(f.tmp[:0], x)")
		g.p("\tf.b.MeasureString(cnfrt.UnsafeSealBytes(f.tmp))")
		g.p("}")
		g.p("")
		g.p("func (f *%s) codec%d(x %s) cnfrt.Span32 {", g.fz, sh.id, sh.goExpr)
		g.p("\tvar c %s", sh.codec.adapter)
		g.p("\tf.tmp = c.Append(f.tmp[:0], x)")
		g.p("\treturn f.b.String(cnfrt.UnsafeSealBytes(f.tmp))")
		g.p("}")
		g.p("")
	case kArrayInline:
		if sh.n == 0 || (g.directArray(sh) && sh.goExpr == sh.flatExpr) {
			return
		}
		g.p("func (f *%s) e%d(x %s) (out %s) {", g.fz, sh.id, sh.goExpr, sh.flatExpr)
		g.p("\tfor i := range x {")
		g.p("\t\tout[i] = %s", g.emit(sh.elem, "x[i]"))
		g.p("\t}")
		g.p("\treturn out")
		g.p("}")
		g.p("")
	case kStructKey:
		if g.needsMeasure(sh) {
			g.p("func (f *%s) m%d(x %s) {", g.fz, sh.id, sh.goExpr)
			for _, fl := range sh.sfields {
				if s := g.measure(fl.sh, "x."+fl.name); s != "" {
					g.p("\t%s", s)
				}
			}
			g.p("}")
			g.p("")
		}
		g.p("func (f *%s) e%d(x %s) (out %s) {", g.fz, sh.id, sh.goExpr, sh.flatExpr)
		for _, fl := range sh.sfields {
			if fl.sh.isZeroArray() {
				continue
			}
			g.p("\tout.%s = %s", fl.flatName, g.emit(fl.sh, "x."+fl.name))
		}
		g.p("\treturn out")
		g.p("}")
		g.p("")
	case kSlice, kArrayPool:
		if sh.kind == kArrayPool && sh.n == 0 {
			return
		}
		p := sh.pool
		g.p("func (f *%s) m%d(x %s) {", g.fz, sh.id, sh.goExpr)
		g.p("\tcnfrt.GrowPool(&f.c%d, len(x))", p.idx)
		if g.needsMeasure(sh.elem) {
			g.p("\tfor i := range x {")
			g.p("\t\t%s", g.measure(sh.elem, "x[i]"))
			g.p("\t}")
		}
		g.p("}")
		g.p("")
		g.p("func (f *%s) e%d(x %s) cnfrt.Span32 {", g.fz, sh.id, sh.goExpr)
		if sh.kind == kSlice {
			g.p("\tif x == nil {")
			g.p("\t\treturn cnfrt.NilSpan")
			g.p("\t}")
		}
		g.p("\tn := len(x)")
		g.p("\tif n == 0 {")
		g.p("\t\treturn cnfrt.Span32{}")
		g.p("\t}")
		g.p("\toff := f.reserve(&f.p%d, f.c%d, n)", p.idx, p.idx)
		g.p("\tdst := f.s.%s[off : int(off)+n]", p.field)
		g.p("\tfor i := range x {")
		g.p("\t\t%s", g.emitPoolElem(sh.elem, "x[i]", "dst[i]"))
		g.p("\t}")
		g.p("\treturn cnfrt.Span32{Off: off, Len: uint32(n)}")
		g.p("}")
		g.p("")
	case kMap:
		g.genMapFreeze(sh)
	case kIface:
		ifc := sh.iface
		g.p("func (f *%s) m%d(x %s) {", g.fz, sh.id, sh.goExpr)
		g.p("\tswitch v := x.(type) {")
		for _, im := range ifc.impls {
			g.p("\tcase %s:", im.expr)
			if im.ptr {
				g.p("\t\tf.mn%d(v)", im.node.tbl)
			} else {
				g.p("\t\tf.mv%d(&v)", im.node.tbl)
			}
		}
		g.p("\t}")
		g.p("}")
		g.p("")
		g.p("func (f *%s) e%d(x %s) cnfrt.VariantTag {", g.fz, sh.id, sh.goExpr)
		g.p("\tswitch v := x.(type) {")
		g.p("\tcase nil:")
		g.p("\t\treturn cnfrt.VariantTag{}")
		for t, im := range ifc.impls {
			g.p("\tcase %s:", im.expr)
			if im.ptr {
				g.p("\t\treturn cnfrt.VariantTag{Tag: %d, ID: f.en%d(v)}", t+1, im.node.tbl)
			} else {
				g.p("\t\treturn cnfrt.VariantTag{Tag: %d, ID: f.ev%d(&v)}", t+1, im.node.tbl)
			}
		}
		g.p("\t}")
		g.p("\tcnfrt.Fail(fmt.Errorf(\"%%w: dynamic type %%T is not listed in the implementations of %s\", cnfrt.ErrUnsupportedType, x))", ifc.name)
		g.p("\treturn cnfrt.VariantTag{}")
		g.p("}")
		g.p("")
	}
}

func (g *gen) genMapFreeze(sh *shape) {
	k, v := sh.mkey, sh.elem
	p := sh.pool
	caches := g.mapCachesKeys(sh)
	g.p("func (f *%s) m%d(x %s) {", g.fz, sh.id, sh.goExpr)
	g.p("\tcnfrt.GrowPool(&f.c%d, len(x))", p.idx)
	if sh.hashed {
		g.p("\tcnfrt.GrowPool(&f.c%d, cnfrt.HashRegion(len(x)))", sh.idxPool.idx)
	}
	nanCheck := func(indent string) {
		if g.keyHasFloat(k) {
			g.p("%sif %s {", indent, g.keyNaNExpr(k, "k"))
			g.p("%s\tcnfrt.Fail(cnfrt.ErrNaNKey)", indent)
			g.p("%s}", indent)
		}
	}
	switch {
	case caches:
		// Visit the entries in the order of the second pass, so that both
		// passes present strings to the interning cache in the same order.
		// Large maps cache their sorted key slice for reuse in the second
		// pass so keys are sorted only once.
		g.p("\tif len(x) == 0 {")
		g.p("\t\treturn")
		g.p("\t}")
		g.p("\tvar keys []%s", k.goExpr)
		g.p("\tcacheLarge := len(x) >= 256")
		g.p("\tif cacheLarge {")
		g.p("\t\tkeys = make([]%s, 0, len(x))", k.goExpr)
		g.p("\t} else {")
		g.p("\t\tkeys = f.k%d[:0]", sh.id)
		g.p("\t\tf.k%d = nil", sh.id)
		g.p("\t\tif cap(keys) < len(x) {")
		g.p("\t\t\tkeys = make([]%s, 0, max(len(x), 2*cap(keys)))", k.goExpr)
		g.p("\t\t}")
		g.p("\t}")
		g.p("\tfor k := range x {")
		nanCheck("\t\t")
		g.p("\t\tkeys = append(keys, k)")
		g.p("\t}")
		g.p("\t%s", g.sortKeys(k, "keys"))
		g.p("\tif cacheLarge {")
		g.p("\t\tf.cached%d = append(f.cached%d, keys)", sh.id, sh.id)
		g.p("\t}")
		g.p("\tfor _, k := range keys {")
		if g.needsMeasure(k) {
			g.p("\t\t%s", g.measure(k, "k"))
		}
		if g.needsMeasure(v) {
			g.p("\t\tv := x[k]")
			g.p("\t\t%s", g.measure(v, "v"))
		}
		g.p("\t}")
		g.p("\tif !cacheLarge {")
		g.p("\t\tf.k%d = keys[:0]", sh.id)
		g.p("\t}")
	case g.keyHasFloat(k):
		g.p("\tfor k := range x {")
		nanCheck("\t\t")
		g.p("\t}")
	}
	g.p("}")
	g.p("")
	ret := "cnfrt.Span32"
	nilRet, emptyRet := "cnfrt.NilSpan", "cnfrt.Span32{}"
	if sh.hashed {
		ret = "cnfrt.HashSpan"
		nilRet, emptyRet = "cnfrt.HashSpan{KV: cnfrt.NilSpan, Idx: cnfrt.NilSpan}", "cnfrt.HashSpan{}"
	}
	g.p("func (f *%s) e%d(x %s) %s {", g.fz, sh.id, sh.goExpr, ret)
	g.p("\tif x == nil {")
	g.p("\t\treturn %s", nilRet)
	g.p("\t}")
	g.p("\tn := len(x)")
	g.p("\tif n == 0 {")
	g.p("\t\treturn %s", emptyRet)
	g.p("\t}")
	g.p("\tvar keys []%s", k.goExpr)
	g.p("\treuseBuf := true")
	if caches {
		g.p("\tif n >= 256 {")
		g.p("\t\tif f.cachedPos%d >= len(f.cached%d) {", sh.id, sh.id)
		g.p("\t\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
		g.p("\t\t}")
		g.p("\t\tkeys = f.cached%d[f.cachedPos%d]", sh.id, sh.id)
		g.p("\t\tf.cached%d[f.cachedPos%d] = nil", sh.id, sh.id)
		g.p("\t\tf.cachedPos%d++", sh.id)
		g.p("\t\tif len(keys) != n {")
		g.p("\t\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
		g.p("\t\t}")
		g.p("\t\treuseBuf = false")
		g.p("\t} else {")
	}
	g.p("\t// Take the shared key buffer; a nested map of the same type finds it")
	g.p("\t// empty and uses its own.")
	g.p("\tkeys = f.k%d[:0]", sh.id)
	g.p("\tf.k%d = nil", sh.id)
	g.p("\tif cap(keys) < n {")
	g.p("\t\tkeys = make([]%s, 0, max(n, 2*cap(keys)))", k.goExpr)
	g.p("\t}")
	g.p("\tfor k := range x {")
	g.p("\t\tkeys = append(keys, k)")
	g.p("\t}")
	g.p("\tif len(keys) != n {")
	g.p("\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
	g.p("\t}")
	g.p("\t%s", g.sortKeys(k, "keys"))
	if caches {
		g.p("\t}")
	}
	g.p("\toff := f.reserve(&f.p%d, f.c%d, n)", p.idx, p.idx)
	g.p("\tdst := f.s.%s[off : int(off)+n]", p.field)
	g.p("\tfor i, k := range keys {")
	if v.isZeroArray() {
		g.p("\t\t_, ok := x[k]")
	} else {
		g.p("\t\tv, ok := x[k]")
	}
	g.p("\t\tif !ok {")
	g.p("\t\t\tcnfrt.Fail(cnfrt.ErrConcurrentModification)")
	g.p("\t\t}")
	if !k.isZeroArray() {
		g.p("\t\tdst[i].K = %s", g.emit(k, "k"))
	}
	if !v.isZeroArray() {
		g.p("\t\t%s", g.emitPoolElem(v, "v", "dst[i].V"))
	}
	if k.isZeroArray() && v.isZeroArray() {
		g.p("\t\t_ = dst[i]")
	}
	g.p("\t}")
	if !sh.hashed {
		g.p("\tif reuseBuf {")
		g.p("\t\tf.k%d = keys[:0]", sh.id)
		g.p("\t}")
		g.p("\treturn cnfrt.Span32{Off: off, Len: uint32(n)}")
		g.p("}")
		g.p("")
		return
	}
	g.p("\tregion := cnfrt.HashRegion(n)")
	g.p("\tioff := f.reserve(&f.p%d, f.c%d, region)", sh.idxPool.idx, sh.idxPool.idx)
	g.p("\tidx := f.s.%s[ioff : int(ioff)+region]", sh.idxPool.field)
	g.p("\tmask := uint64(region - 1)")
	g.p("\tfor i, k := range keys {")
	g.p("\t\th := %s", g.keyHash(k, "k", "f.b.Seed"))
	g.p("\t\tfor j := h & mask; ; j = (j + 1) & mask {")
	g.p("\t\t\tif idx[j] == 0 {")
	g.p("\t\t\t\tidx[j] = uint32(i + 1)")
	g.p("\t\t\t\tbreak")
	g.p("\t\t\t}")
	g.p("\t\t}")
	g.p("\t}")
	g.p("\tif reuseBuf {")
	g.p("\t\tf.k%d = keys[:0]", sh.id)
	g.p("\t}")
	g.p("\treturn cnfrt.HashSpan{KV: cnfrt.Span32{Off: off, Len: uint32(n)}, Idx: cnfrt.Span32{Off: ioff, Len: uint32(region)}}")
	g.p("}")
	g.p("")
}

func (g *gen) genFreezeEntry(r *node) {
	sc := g.sc
	fn := sc.prefix + r.name
	g.p("// Freeze%s freezes the object graph rooted at src into a snapshot.", fn)
	if sc.treeDefault {
		g.p("// The graph is treated as a tree (see FreezeTree%s).", fn)
	} else {
		g.p("// Shared pointers are deduplicated and directed cycles are rejected with")
		g.p("// cnfrt.ErrCycleDetected.")
	}
	g.p("func Freeze%s(src *%s, opts ...cnfrt.FreezeOption) (*%s, error) {", fn, r.goExpr, g.snap)
	if sc.treeDefault {
		g.p("\treturn track%s(freezeTree%s(src, opts))", g.snap, fn)
	} else {
		g.p("\treturn track%s(freeze%s(cnfrt.ModeDAG, src, opts))", g.snap, fn)
	}
	g.p("}")
	g.p("")
	g.p("// FreezeTree%s freezes src as a tree: no visited set is kept (shared", fn)
	g.p("// pointers are duplicated) and recursion deeper than the maximum depth fails")
	g.p("// with cnfrt.ErrCycleDetected. Because addresses are not recorded, src does")
	g.p("// not need to escape to the heap.")
	g.p("func FreezeTree%s(src *%s, opts ...cnfrt.FreezeOption) (*%s, error) {", fn, r.goExpr, g.snap)
	g.p("\treturn track%s(freezeTree%s(src, opts))", g.snap, fn)
	g.p("}")
	g.p("")
	g.p("// FreezeCyclic%s freezes src permitting directed cycles; shared pointers are", fn)
	g.p("// deduplicated.")
	g.p("func FreezeCyclic%s(src *%s, opts ...cnfrt.FreezeOption) (*%s, error) {", fn, r.goExpr, g.snap)
	g.p("\treturn track%s(freeze%s(cnfrt.ModeCyclic, src, opts))", g.snap, fn)
	g.p("}")
	g.p("")
	g.p("func freeze%s(mode cnfrt.FreezeMode, src *%s, opts []cnfrt.FreezeOption) (snap *%s, err error) {", fn, r.goExpr, g.snap)
	g.p("\tif src == nil {")
	g.p("\t\treturn nil, cnfrt.ErrNilRoot")
	g.p("\t}")
	g.p("\tcnfrt.Escape(src)")
	g.p("\tf := %sPool.Get().(*%s)", g.fz, g.fz)
	g.p("\tdefer func() {")
	g.p("\t\tcnfrt.Recover(recover(), &err)")
	g.p("\t\tif err != nil {")
	g.p("\t\t\tsnap = nil")
	g.p("\t\t}")
	g.p("\t\tf.reset()")
	g.p("\t\t%sPool.Put(f)", g.fz)
	g.p("\t}()")
	g.p("\tf.b.Init(mode, %d, opts...)", len(sc.tableNodes()))
	g.p("\tf.mn%d(src)", r.tbl)
	g.p("\tf.allocate()")
	g.p("\tid := f.en%d(src)", r.tbl)
	g.p("\tf.finish()")
	g.p("\truntime.KeepAlive(src)")
	g.p("\ts := f.s")
	g.p("\ts.rootTable, s.rootID = %d, id", r.tbl)
	g.p("\treturn s, nil")
	g.p("}")
	g.p("")
	g.p("func freezeTree%s(src *%s, opts []cnfrt.FreezeOption) (snap *%s, err error) {", fn, r.goExpr, g.snap)
	g.p("\tif src == nil {")
	g.p("\t\treturn nil, cnfrt.ErrNilRoot")
	g.p("\t}")
	g.p("\tf := %sPool.Get().(*%s)", g.fz, g.fz)
	g.p("\tdefer func() {")
	g.p("\t\tcnfrt.Recover(recover(), &err)")
	g.p("\t\tif err != nil {")
	g.p("\t\t\tsnap = nil")
	g.p("\t\t}")
	g.p("\t\tf.reset()")
	g.p("\t\t%sPool.Put(f)", g.fz)
	g.p("\t}()")
	g.p("\tf.b.Init(cnfrt.ModeTree, %d, opts...)", len(sc.tableNodes()))
	g.p("\tf.mn%d(src)", r.tbl)
	g.p("\tf.allocate()")
	g.p("\tid := f.en%d(src)", r.tbl)
	g.p("\tf.finish()")
	g.p("\truntime.KeepAlive(src)")
	g.p("\ts := f.s")
	g.p("\ts.rootTable, s.rootID = %d, id", r.tbl)
	g.p("\treturn s, nil")
	g.p("}")
	g.p("")
}

// --- unfreezer ---------------------------------------------------------------------------

func (g *gen) unfreeze(sh *shape, x string) string {
	switch sh.kind {
	case kScalar:
		return g.scalarRead(sh, x)
	case kString:
		e := "u.s.str(" + x + ")"
		if sh.goExpr != "string" {
			e = sh.goExpr + "(" + e + ")"
		}
		return e
	case kBytes:
		if sh.goExpr != "[]byte" {
			return sh.goExpr + "(u.bytes(" + x + "))"
		}
		return "u.bytes(" + x + ")"
	case kTime, kAddr, kPrefix, kAddrPort:
		return g.read(sh, x, "u.s")
	case kCodec:
		return fmt.Sprintf("u.codec%d(%s)", sh.id, x)
	case kNode:
		if sh.node.inlined {
			return fmt.Sprintf("u.vi%d(%s)", sh.node.inlineID, x)
		}
		return fmt.Sprintf("u.vn%d(%s)", sh.node.tbl, x)
	case kPtrNode:
		return fmt.Sprintf("u.pn%d(%s)", sh.node.tbl, x)
	case kArrayInline:
		if sh.n == 0 {
			return sh.goExpr + "{}"
		}
		if g.directArray(sh) && sh.goExpr == sh.flatExpr {
			return x
		}
		return fmt.Sprintf("u.u%d(%s)", sh.id, x)
	case kArrayPool:
		if sh.n == 0 {
			return sh.goExpr + "{}"
		}
		return fmt.Sprintf("u.u%d(%s)", sh.id, x)
	case kStructKey:
		return fmt.Sprintf("u.skey%d(%s)", sh.id, x)
	}
	return fmt.Sprintf("u.u%d(%s)", sh.id, x)
}

// unfreezePoolElem returns statements setting dst from the pool element src.
func (g *gen) unfreezePoolElem(sh *shape, src, dst string) string {
	if sh.kind == kOptional {
		if sh.elem.isZeroArray() {
			return fmt.Sprintf("if %s.P != 0 { var optVal %s; %s = &optVal }", src, sh.elem.goExpr, dst)
		}
		return fmt.Sprintf("if %s.P != 0 { optVal := %s; %s = &optVal }", src, g.unfreeze(sh.elem, src+".V"), dst)
	}
	if sh.isZeroArray() {
		return fmt.Sprintf("_ = %s; %s = %s{}", src, dst, sh.goExpr)
	}
	return dst + " = " + g.unfreeze(sh, src)
}

func (g *gen) genUnfreezer() {
	sc := g.sc
	g.p("type %s struct {", g.uf)
	g.p("\ts   *%s", g.snap)
	g.p("\terr error")
	g.p("\t// depth counts nested value nodes; it cannot exceed the number of")
	g.p("\t// nodes unless a (corrupt) image contains a value-node cycle.")
	g.p("\tdepth int")
	for _, n := range sc.tableNodes() {
		g.p("\tm%d []*%s", n.tbl, n.goExpr)
	}
	g.p("}")
	g.p("")
	g.p("func (u *%s) bytes(x cnfrt.Span32) []byte {", g.uf)
	g.p("\tif x.Off == cnfrt.NilSpanOff {")
	g.p("\t\treturn nil")
	g.p("\t}")
	g.p("\treturn []byte(u.s.rawStr(x))")
	g.p("}")
	g.p("")
	for _, n := range sc.inlineNodes() {
		id := n.inlineID
		g.p("func (u *%s) filli%d(r *%s, p *%s) {", g.uf, id, n.flatName, n.goExpr)
		for _, fl := range n.fields {
			if fl.sh.kind == kOptional {
				g.p("\tif %s {", presenceTest(n, fl.optBit, "r"))
				if fl.sh.elem.isZeroArray() {
					g.p("\t\tvar optVal %s", fl.sh.elem.goExpr)
				} else {
					g.p("\t\toptVal := %s", g.unfreeze(fl.sh.elem, "r."+fl.flatName))
				}
				g.p("\t\tp.%s = &optVal", fl.name)
				g.p("\t}")
				continue
			}
			if fl.sh.isZeroArray() {
				continue
			}
			g.p("\tp.%s = %s", fl.name, g.unfreeze(fl.sh, "r."+fl.flatName))
		}
		g.p("}")
		g.p("")
		g.p("func (u *%s) vi%d(r %s) (x %s) {", g.uf, id, n.flatName, n.goExpr)
		g.p("\tu.filli%d(&r, &x)", id)
		g.p("\treturn x")
		g.p("}")
		g.p("")
	}
	for _, n := range sc.tableNodes() {
		t := n.tbl
		g.p("func (u *%s) fill%d(id uint32, p *%s) {", g.uf, t, n.goExpr)
		hasRealField := false
		for _, fl := range n.fields {
			if !fl.sh.isZeroArray() {
				hasRealField = true
				break
			}
		}
		if hasRealField {
			g.p("\tr := &u.s.%s", g.nodeIndex(n, "id"))
			for _, fl := range n.fields {
				if fl.sh.kind == kOptional {
					g.p("\tif %s {", presenceTest(n, fl.optBit, "r"))
					if fl.sh.elem.isZeroArray() {
						g.p("\t\tvar optVal %s", fl.sh.elem.goExpr)
					} else {
						g.p("\t\toptVal := %s", g.unfreeze(fl.sh.elem, "r."+fl.flatName))
					}
					g.p("\t\tp.%s = &optVal", fl.name)
					g.p("\t}")
					continue
				}
				if fl.sh.isZeroArray() {
					continue
				}
				g.p("\tp.%s = %s", fl.name, g.unfreeze(fl.sh, "r."+fl.flatName))
			}
		}
		g.p("}")
		g.p("")
		g.p("func (u *%s) pn%d(id uint32) *%s {", g.uf, t, n.goExpr)
		g.p("\tif id == 0 {")
		g.p("\t\treturn nil")
		g.p("\t}")
		g.p("\tif u.m%d == nil {", t)
		g.p("\t\tu.m%d = make([]*%s, len(u.s.nodes%s))", t, n.goExpr, n.name)
		g.p("\t}")
		g.p("\tif p := u.m%d[id-1]; p != nil {", t)
		g.p("\t\treturn p")
		g.p("\t}")
		g.p("\tp := new(%s)", n.goExpr)
		g.p("\tu.m%d[id-1] = p", t)
		g.p("\tu.fill%d(id, p)", t)
		g.p("\treturn p")
		g.p("}")
		g.p("")
		g.p("func (u *%s) vn%d(id uint32) (x %s) {", g.uf, t, n.goExpr)
		g.p("\tif id == 0 || u.depth > u.s.nodeCount() {")
		g.p("\t\tif u.err == nil {")
		g.p("\t\t\tu.err = fmt.Errorf(\"%%w: value node cycle\", cnfrt.ErrCycleDetected)")
		g.p("\t\t}")
		g.p("\t\treturn x")
		g.p("\t}")
		g.p("\tu.depth++")
		g.p("\tu.fill%d(id, &x)", t)
		g.p("\tu.depth--")
		g.p("\treturn x")
		g.p("}")
		g.p("")
	}
	for _, sh := range sc.shapes {
		switch sh.kind {
		case kCodec:
			g.p("func (u *%s) codec%d(x cnfrt.Span32) %s {", g.uf, sh.id, sh.goExpr)
			g.p("\tvar c %s", sh.codec.adapter)
			g.p("\tv, err := c.Decode(u.s.str(x))")
			g.p("\tif err != nil && u.err == nil {")
			g.p("\t\tu.err = err")
			g.p("\t}")
			g.p("\treturn v")
			g.p("}")
			g.p("")
		case kArrayInline:
			if sh.n == 0 || (g.directArray(sh) && sh.goExpr == sh.flatExpr) {
				continue
			}
			g.p("func (u *%s) u%d(x %s) (out %s) {", g.uf, sh.id, sh.flatExpr, sh.goExpr)
			g.p("\tfor i := range x {")
			g.p("\t\tout[i] = %s", g.unfreeze(sh.elem, "x[i]"))
			g.p("\t}")
			g.p("\treturn out")
			g.p("}")
			g.p("")
		case kStructKey:
			g.p("func (u *%s) skey%d(x %s) (out %s) {", g.uf, sh.id, sh.flatExpr, sh.goExpr)
			for _, f := range sh.sfields {
				if f.sh.isZeroArray() {
					continue
				}
				g.p("\tout.%s = %s", f.name, g.unfreeze(f.sh, "x."+f.flatName))
			}
			g.p("\treturn out")
			g.p("}")
			g.p("")
		case kSlice:
			g.p("func (u *%s) u%d(x cnfrt.Span32) %s {", g.uf, sh.id, sh.goExpr)
			g.p("\tif x.Off == cnfrt.NilSpanOff {")
			g.p("\t\treturn nil")
			g.p("\t}")
			g.p("\tsrc := u.s.%s[int(x.Off) : int(x.Off)+int(x.Len)]", sh.pool.field)
			g.p("\tout := make(%s, len(src))", sh.goExpr)
			g.p("\tfor i := range src {")
			g.p("\t\t%s", g.unfreezePoolElem(sh.elem, "src[i]", "out[i]"))
			g.p("\t}")
			g.p("\treturn out")
			g.p("}")
			g.p("")
		case kArrayPool:
			if sh.n == 0 {
				continue
			}
			g.p("func (u *%s) u%d(x cnfrt.Span32) (out %s) {", g.uf, sh.id, sh.goExpr)
			g.p("\tsrc := u.s.%s[int(x.Off) : int(x.Off)+int(x.Len)]", sh.pool.field)
			g.p("\tfor i := range src {")
			g.p("\t\t%s", g.unfreezePoolElem(sh.elem, "src[i]", "out[i]"))
			g.p("\t}")
			g.p("\treturn out")
			g.p("}")
			g.p("")
		case kMap:
			span := "x"
			arg := "cnfrt.Span32"
			if sh.hashed {
				span, arg = "x.KV", "cnfrt.HashSpan"
			}
			g.p("func (u *%s) u%d(x %s) %s {", g.uf, sh.id, arg, sh.goExpr)
			g.p("\tif %s.Off == cnfrt.NilSpanOff {", span)
			g.p("\t\treturn nil")
			g.p("\t}")
			g.p("\tsrc := u.s.%s[int(%s.Off) : int(%s.Off)+int(%s.Len)]", sh.pool.field, span, span, span)
			g.p("\tout := make(%s, len(src))", sh.goExpr)
			if sh.mkey.isZeroArray() && sh.elem.isZeroArray() {
				g.p("\tfor range src {")
				g.p("\t\tvar v %s", sh.elem.goExpr)
				g.p("\t\tout[%s] = v", g.unfreeze(sh.mkey, ""))
				g.p("\t}")
			} else {
				g.p("\tfor i := range src {")
				g.p("\t\tvar v %s", sh.elem.goExpr)
				if !sh.elem.isZeroArray() {
					g.p("\t\t%s", g.unfreezePoolElem(sh.elem, "src[i].V", "v"))
				}
				if sh.mkey.isZeroArray() {
					g.p("\t\tout[%s] = v", g.unfreeze(sh.mkey, ""))
				} else {
					g.p("\t\tout[%s] = v", g.unfreeze(sh.mkey, "src[i].K"))
				}
				g.p("\t}")
			}
			g.p("\treturn out")
			g.p("}")
			g.p("")
		case kIface:
			g.p("func (u *%s) u%d(x cnfrt.VariantTag) %s {", g.uf, sh.id, sh.goExpr)
			g.p("\tswitch x.Tag {")
			for t, im := range sh.iface.impls {
				g.p("\tcase %d:", t+1)
				if im.ptr {
					g.p("\t\treturn u.pn%d(x.ID)", im.node.tbl)
				} else {
					g.p("\t\treturn u.vn%d(x.ID)", im.node.tbl)
				}
			}
			g.p("\t}")
			g.p("\treturn nil")
			g.p("}")
			g.p("")
		}
	}
	for _, r := range sc.roots {
		g.p("// Unfreeze%s rebuilds the root %s and everything reachable from it.", r.name, r.name)
		g.p("func (s *%s) Unfreeze%s() (*%s, error) {", g.snap, r.name, r.goExpr)
		g.p("\tif s.rootTable != %d {", r.tbl)
		g.p("\t\treturn nil, fmt.Errorf(\"cnfgo: snapshot root is not a %s\")", r.name)
		g.p("\t}")
		g.p("\treturn s.Root%s().Unfreeze()", r.name)
		g.p("}")
		g.p("")
	}
}

// --- validator ---------------------------------------------------------------------------

func (g *gen) nodeNeedsValidate(n *node) bool {
	if !n.inlined {
		return true
	}
	for _, fl := range n.fields {
		if g.needsValidate(fl.sh) {
			return true
		}
	}
	return false
}

func (g *gen) needsValidate(sh *shape) bool {
	if sh.isZeroArray() {
		return false
	}
	switch sh.kind {
	case kScalar:
		return sh.sc.isBool
	case kArrayInline, kOptional:
		return g.needsValidate(sh.elem)
	case kNode:
		return g.nodeNeedsValidate(sh.node)
	}
	return true
}

func (g *gen) validate(sh *shape, x string) string {
	switch sh.kind {
	case kScalar:
		return "v.bool(" + x + ")"
	case kArrayInline:
		i := "j" + strconv.Itoa(strings.Count(x, "["))
		return "for " + i + " := range " + x + " { " + g.validate(sh.elem, x+"["+i+"]") + " }"
	case kString, kCodec:
		return "v.str(" + x + ")"
	case kBytes:
		return "v.bytes(" + x + ")"
	case kTime:
		return "v.time(" + x + ")"
	case kAddr:
		return "v.addr(" + x + ")"
	case kPrefix:
		return "v.prefix(" + x + ")"
	case kAddrPort:
		return "v.addr(" + x + ".Addr)"
	case kNode:
		if sh.node.inlined {
			return fmt.Sprintf("v.vi%d(&%s, self, tbl)", sh.node.inlineID, x)
		}
		return fmt.Sprintf("v.ref(%d, %s, false, self, tbl)", sh.node.tbl, x)
	case kPtrNode:
		return fmt.Sprintf("v.ref(%d, %s, true, self, tbl)", sh.node.tbl, x)
	}
	return fmt.Sprintf("v.v%d(%s, self, tbl)", sh.id, x)
}

func (g *gen) validatePoolElem(sh *shape, x string) string {
	if sh.kind == kOptional {
		s := fmt.Sprintf("if %s.P > 1 { v.fail(\"optional flag\") }", x)
		if g.needsValidate(sh.elem) {
			s += fmt.Sprintf(" else if %s.P == 1 { %s }", x, g.validate(sh.elem, x+".V"))
		}
		return s
	}
	return g.validate(sh, x)
}

func (g *gen) keyHasString(k *shape) bool {
	switch k.kind {
	case kString, kAddr, kAddrPort:
		return true
	case kStructKey:
		for _, f := range k.sfields {
			if g.keyHasString(f.sh) {
				return true
			}
		}
	}
	return false
}

func (g *gen) genKeyDebit(k *shape, x, indent string) {
	switch k.kind {
	case kString:
		g.p("%sif !v.debit(uint64(%s.Len) + 1) {", indent, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kAddr:
		g.p("%sif !v.debitAddr(%s) {", indent, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kAddrPort:
		g.p("%sif !v.debitAddr(%s.Addr) {", indent, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kStructKey:
		for _, f := range k.sfields {
			if g.keyHasString(f.sh) {
				g.genKeyDebit(f.sh, x+"."+f.flatName, indent)
			}
		}
	}
}

func (g *gen) genKeyValidate(k *shape, x, indent string) {
	switch k.kind {
	case kString:
		g.p("%sif !v.str(%s) || !v.debit(uint64(%s.Len)+1) {", indent, x, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kScalar:
		if k.sc.isFloat {
			g.p("%sif %s != %s {", indent, x, x)
			g.p("%s\tv.fail(\"NaN map key\")", indent)
			g.p("%s\treturn", indent)
			g.p("%s}", indent)
		}
		if k.sc.isBool {
			g.p("%sif %s > 1 {", indent, x)
			g.p("%s\tv.fail(\"boolean map key\")", indent)
			g.p("%s\treturn", indent)
			g.p("%s}", indent)
		}
	case kAddr:
		g.p("%sv.addr(%s)", indent, x)
		g.p("%sif v.err != nil || !v.debitAddr(%s) {", indent, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kPrefix:
		g.p("%sv.prefix(%s)", indent, x)
		g.p("%sif v.err != nil {", indent)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kAddrPort:
		g.p("%sv.addr(%s.Addr)", indent, x)
		g.p("%sif v.err != nil || !v.debitAddr(%s.Addr) {", indent, x)
		g.p("%s\treturn", indent)
		g.p("%s}", indent)
	case kArrayInline:
		if k.n > 0 && (k.elem.sc.isFloat || k.elem.sc.isBool) {
			g.p("%sfor _, ke := range %s {", indent, x)
			g.genKeyValidate(k.elem, "ke", indent+"\t")
			g.p("%s}", indent)
		}
	case kStructKey:
		for _, f := range k.sfields {
			if f.sh.isZeroArray() {
				continue
			}
			g.genKeyValidate(f.sh, x+"."+f.flatName, indent)
		}
	}
}

func (g *gen) genValidator() {
	sc := g.sc
	g.p("type %s struct {", g.vd)
	g.p("\ts          *%s", g.snap)
	g.p("\terr        error")
	g.p("\tcyclic     bool")
	g.p("\tclaims     []cnfrt.Claims")
	g.p("\tworkBudget uint64")
	g.p("}")
	g.p("")
	g.p("func (v *%s) fail(what string) {", g.vd)
	g.p("\tif v.err == nil {")
	g.p("\t\tv.err = fmt.Errorf(\"%%w: %%s\", cnfrt.ErrBoundsViolation, what)")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) failErr(err error) {", g.vd)
	g.p("\tif v.err == nil {")
	g.p("\t\tv.err = err")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) debit(n uint64) bool {", g.vd)
	g.p("\tif n > v.workBudget {")
	g.p("\t\tv.fail(\"validation work budget exceeded\")")
	g.p("\t\treturn false")
	g.p("\t}")
	g.p("\tv.workBudget -= n")
	g.p("\treturn true")
	g.p("}")
	g.p("")
	g.p("func (v *%s) str(x cnfrt.Span32) bool {", g.vd)
	g.p("\tif x.Off&cnfrt.DictSpanBit != 0 {")
	g.p("\t\tif v.s.dict == nil || !v.s.dict.ValidCapturedSpan(v.s.dictStrs, x) {")
	g.p("\t\t\tv.fail(\"dict string span\")")
	g.p("\t\t\treturn false")
	g.p("\t\t}")
	g.p("\t\treturn true")
	g.p("\t}")
	g.p("\tif x.Off == cnfrt.NilSpanOff || x.End() > uint64(len(v.s.strBlob)) {")
	g.p("\t\tv.fail(\"string span\")")
	g.p("\t\treturn false")
	g.p("\t}")
	g.p("\treturn true")
	g.p("}")
	g.p("")
	g.p("func (v *%s) bool(x uint8) {", g.vd)
	g.p("\tif x > 1 {")
	g.p("\t\tv.fail(\"boolean\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) bytes(x cnfrt.Span32) {", g.vd)
	g.p("\tif !x.InBounds(len(v.s.strBlob)) {")
	g.p("\t\tv.fail(\"byte span\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) time(x cnfrt.FlatTime) {", g.vd)
	g.p("\tif !x.Valid(len(v.s.locs)) {")
	g.p("\t\tv.fail(\"time\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) addr(x cnfrt.FlatAddr) {", g.vd)
	g.p("\tif !x.Valid(len(v.s.zoned)) {")
	g.p("\t\tv.fail(\"address\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) debitAddr(x cnfrt.FlatAddr) bool {", g.vd)
	g.p("\tn := uint64(1)")
	g.p("\tif x.Kind == cnfrt.AddrV6Zoned {")
	g.p("\t\tn += uint64(len(v.s.zoned[x.ZonedIdx-1].Zone()))")
	g.p("\t}")
	g.p("\treturn v.debit(n)")
	g.p("}")
	g.p("")
	g.p("func (v *%s) prefix(x cnfrt.FlatPrefix) {", g.vd)
	g.p("\tif !x.Valid() {")
	g.p("\t\tv.fail(\"prefix\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (v *%s) tableLen(tbl int) int {", g.vd)
	g.p("\tswitch tbl {")
	for _, n := range sc.tableNodes() {
		g.p("\tcase %d:", n.tbl)
		g.p("\t\treturn len(v.s.nodes%s)", n.name)
	}
	g.p("\t}")
	g.p("\treturn 0")
	g.p("}")
	g.p("")
	g.p("// ref checks a node reference from node self of table owner: it must be in")
	g.p("// bounds and, unless cycles are allowed, satisfy childID > selfID within a table.")
	g.p("func (v *%s) ref(tbl int, id uint32, nilOK bool, self uint32, owner int) {", g.vd)
	g.p("\tswitch {")
	g.p("\tcase id == 0 && !nilOK:")
	g.p("\t\tv.fail(\"nil value node\")")
	g.p("\tcase uint64(id) > uint64(v.tableLen(tbl)):")
	g.p("\t\tv.fail(\"node ID out of range\")")
	g.p("\tcase !v.cyclic && id != 0 && tbl == owner && id <= self:")
	g.p("\t\tv.fail(\"childID > selfID invariant violated\")")
	g.p("\t}")
	g.p("}")
	g.p("")
	for _, sh := range sc.shapes {
		g.genShapeValidate(sh)
	}
	for _, n := range sc.inlineNodes() {
		if !g.nodeNeedsValidate(n) {
			continue
		}
		g.p("func (v *%s) vi%d(r *%s, self uint32, tbl int) {", g.vd, n.inlineID, n.flatName)
		for _, fl := range n.fields {
			if !g.needsValidate(fl.sh) {
				continue
			}
			if fl.sh.kind == kOptional {
				g.p("\tif %s {", presenceTest(n, fl.optBit, "r"))
				g.p("\t\t%s", g.validate(fl.sh.elem, "r."+fl.flatName))
				g.p("\t}")
				continue
			}
			g.p("\t%s", g.validate(fl.sh, "r."+fl.flatName))
		}
		g.p("}")
		g.p("")
	}
	for _, n := range sc.tableNodes() {
		g.p("func (v *%s) row%d(r *%s, self uint32) {", g.vd, n.tbl, n.flatName)
		g.p("\ttbl := %d", n.tbl)
		g.p("\t_ = tbl")
		for _, fl := range n.fields {
			if !g.needsValidate(fl.sh) {
				continue
			}
			if fl.sh.kind == kOptional {
				g.p("\tif %s {", presenceTest(n, fl.optBit, "r"))
				g.p("\t\t%s", g.validate(fl.sh.elem, "r."+fl.flatName))
				g.p("\t}")
				continue
			}
			g.p("\t%s", g.validate(fl.sh, "r."+fl.flatName))
		}
		g.p("}")
		g.p("")
	}
	g.p("func (s *%s) validate() error {", g.snap)
	g.p("\tv := &%s{s: s, cyclic: s.flags&cnfrt.FlagCyclicAllowed != 0, claims: make([]cnfrt.Claims, %d), workBudget: 32*uint64(s.SizeBytes()) + 65536}", g.vd, len(sc.pools))
	g.p("\tfor _, a := range s.zoned {")
	g.p("\t\tv.workBudget += 32 * uint64(len(a.Zone()))")
	g.p("\t}")
	g.p("\tif s.dict != nil {")
	g.p("\t\t// Strings of an allowed Dict are compared during validation too;")
	g.p("\t\t// their budget stays linear in the dictionary size.")
	g.p("\t\tv.workBudget += min(32*s.dict.Stats().Bytes, 64<<20)")
	g.p("\t}")
	for _, p := range sc.pools {
		g.p("\tv.claims[%d] = cnfrt.NewClaims(len(s.%s))", p.idx, p.field)
	}
	for _, n := range sc.tableNodes() {
		g.p("\tfor i := range s.nodes%s {", n.name)
		g.p("\t\tv.row%d(&s.nodes%s[i], uint32(i+1))", n.tbl, n.name)
		g.p("\t\tif v.err != nil {")
		g.p("\t\t\treturn v.err")
		g.p("\t\t}")
		g.p("\t}")
	}
	if sc.crossSCC {
		g.p("\tif !v.cyclic {")
		g.p("\t\tif err := cnfrt.CheckAcyclic(%s{s}); err != nil {", g.gr)
		g.p("\t\t\treturn err")
		g.p("\t\t}")
		g.p("\t}")
	}
	g.p("\treturn nil")
	g.p("}")
	g.p("")
	if sc.crossSCC {
		g.genGraph()
	}
}

func (g *gen) genShapeValidate(sh *shape) {
	switch sh.kind {
	case kSlice, kArrayPool:
		if sh.kind == kArrayPool && sh.n == 0 {
			return
		}
		p := sh.pool
		exact, nilOK := "-1", "true"
		if sh.kind == kArrayPool {
			exact, nilOK = strconv.FormatInt(sh.n, 10), "false"
		}
		g.p("func (v *%s) v%d(x cnfrt.Span32, self uint32, tbl int) {", g.vd, sh.id)
		g.p("\tif err := v.claims[%d].Claim(x, %s, %s); err != nil {", p.idx, exact, nilOK)
		g.p("\t\tv.failErr(err)")
		g.p("\t\treturn")
		g.p("\t}")
		if g.needsValidate(sh.elem) {
			g.p("\tif x.Len == 0 {")
			g.p("\t\treturn")
			g.p("\t}")
			g.p("\telems := v.s.%s[int(x.Off):int(x.Off)+int(x.Len)]", p.field)
			g.p("\tfor i := range elems {")
			g.p("\t\t%s", g.validatePoolElem(sh.elem, "elems[i]"))
			g.p("\t}")
		}
		g.p("}")
		g.p("")
	case kMap:
		k := sh.mkey
		arg, span := "cnfrt.Span32", "x"
		if sh.hashed {
			arg, span = "cnfrt.HashSpan", "x.KV"
		}
		g.p("func (v *%s) v%d(x %s, self uint32, tbl int) {", g.vd, sh.id, arg)
		g.p("\tif err := v.claims[%d].Claim(%s, -1, true); err != nil {", sh.pool.idx, span)
		g.p("\t\tv.failErr(err)")
		g.p("\t\treturn")
		g.p("\t}")
		if sh.hashed {
			g.p("\tregion := cnfrt.HashRegion(int(x.KV.Len))")
			g.p("\tif err := v.claims[%d].Claim(x.Idx, region, x.KV.Off == cnfrt.NilSpanOff); err != nil {", sh.idxPool.idx)
			g.p("\t\tv.failErr(err)")
			g.p("\t\treturn")
			g.p("\t}")
			g.p("\tvar idx []uint32")
			g.p("\tif region > 0 {")
			g.p("\t\tidx = v.s.%s[int(x.Idx.Off) : int(x.Idx.Off)+region]", sh.idxPool.field)
			g.p("\t\tused := 0")
			g.p("\t\tfor _, slot := range idx {")
			g.p("\t\t\tif slot > x.KV.Len {")
			g.p("\t\t\t\tv.fail(\"hash index slot\")")
			g.p("\t\t\t\treturn")
			g.p("\t\t\t}")
			g.p("\t\t\tif slot != 0 {")
			g.p("\t\t\t\tused++")
			g.p("\t\t\t}")
			g.p("\t\t}")
			g.p("\t\t// Exactly one slot per entry leaves at least half of the region")
			g.p("\t\t// empty, so every probe sequence ends early.")
			g.p("\t\tif used != int(x.KV.Len) {")
			g.p("\t\t\tv.fail(\"hash index occupancy\")")
			g.p("\t\t\treturn")
			g.p("\t\t}")
			g.p("\t}")
		}
		g.p("\tif %s.Len == 0 {", span)
		g.p("\t\treturn")
		g.p("\t}")
		g.p("\tkv := v.s.%s[int(%s.Off):int(%s.Off)+int(%s.Len)]", sh.pool.field, span, span, span)
		g.p("\tfor i := range kv {")
		if k.isZeroArray() && !g.needsValidate(sh.elem) {
			g.p("\t\tif i > 0 {")
			g.p("\t\t\tv.fail(\"map keys not strictly ascending\")")
			g.p("\t\t\treturn")
			g.p("\t\t}")
		} else {
			g.p("\t\te := &kv[i]")
			if !k.isZeroArray() {
				g.genKeyValidate(k, "e.K", "\t\t")
			}
			g.p("\t\tif i > 0 && %s >= 0 {", g.flatKeyCompare(k, "kv[i-1].K", "e.K", "v.s"))
			g.p("\t\t\tv.fail(\"map keys not strictly ascending\")")
			g.p("\t\t\treturn")
			g.p("\t\t}")
			if g.needsValidate(sh.elem) {
				g.p("\t\t%s", g.validatePoolElem(sh.elem, "e.V"))
			}
		}
		g.p("\t}")
		if sh.hashed {
			g.p("\t// Every entry must be found by the probe sequence of its key, as Get")
			g.p("\t// searches it, within a linear probe budget.")
			g.p("\tmask := uint64(region - 1)")
			g.p("\tvar totalProbes uint64")
			g.p("\tprobeBudget := uint64(8*len(kv) + 64)")
			g.p("\tfor i := range kv {")
			if g.keyHasString(k) {
				g.genKeyDebit(k, "kv[i].K", "\t\t")
			}
			g.p("\t\th := %s", g.flatKeyHash(k, "kv[i].K", "v.s.seed", "v.s"))
			g.p("\t\tfound := false")
			g.p("\t\tfor probe := range uint64(region) {")
			g.p("\t\t\ttotalProbes++")
			g.p("\t\t\tif totalProbes > probeBudget {")
			g.p("\t\t\t\tv.fail(\"hash index probe budget exceeded\")")
			g.p("\t\t\t\treturn")
			g.p("\t\t\t}")
			g.p("\t\t\tslot := idx[(h+probe)&mask]")
			g.p("\t\t\tif slot == 0 {")
			g.p("\t\t\t\tbreak")
			g.p("\t\t\t}")
			g.p("\t\t\tif slot == uint32(i+1) {")
			g.p("\t\t\t\tfound = true")
			g.p("\t\t\t\tbreak")
			g.p("\t\t\t}")
			g.p("\t\t}")
			g.p("\t\tif !found {")
			g.p("\t\t\tv.fail(\"hash index does not locate a key\")")
			g.p("\t\t\treturn")
			g.p("\t\t}")
			g.p("\t}")
		}
		g.p("}")
		g.p("")
	case kIface:
		ifc := sh.iface
		g.p("func (v *%s) v%d(x cnfrt.VariantTag, self uint32, tbl int) {", g.vd, sh.id)
		g.p("\tif x.Pad != 0 {")
		g.p("\t\tv.fail(\"variant padding\")")
		g.p("\t\treturn")
		g.p("\t}")
		g.p("\tswitch x.Tag {")
		g.p("\tcase 0:")
		g.p("\t\tif x.ID != 0 {")
		g.p("\t\t\tv.fail(\"nil variant with ID\")")
		g.p("\t\t}")
		for t, im := range ifc.impls {
			g.p("\tcase %d:", t+1)
			g.p("\t\tv.ref(%d, x.ID, %v, self, tbl)", im.node.tbl, im.ptr)
		}
		g.p("\tdefault:")
		g.p("\t\tv.fail(\"variant tag\")")
		g.p("\t}")
		g.p("}")
		g.p("")
	}
}

// edges returns a statement visiting the node references in flat value x.
func (g *gen) edges(sh *shape, x string) string {
	switch sh.kind {
	case kNode:
		if sh.node.inlined {
			return fmt.Sprintf("g.gi%d(&%s, visit)", sh.node.inlineID, x)
		}
		return fmt.Sprintf("visit(%d, %s)", sh.node.tbl, x)
	case kPtrNode:
		return fmt.Sprintf("visit(%d, %s)", sh.node.tbl, x)
	case kSlice, kArrayPool, kMap, kIface:
		return fmt.Sprintf("g.g%d(%s, visit)", sh.id, x)
	}
	return ""
}

func (g *gen) genGraph() {
	sc := g.sc
	gt := g.gr
	g.p("type %s struct{ s *%s }", gt, g.snap)
	g.p("")
	g.p("func (g %s) TableLens() []int {", gt)
	g.p("\treturn []int{")
	for _, n := range sc.tableNodes() {
		g.p("\t\tlen(g.s.nodes%s),", n.name)
	}
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p("func (g %s) Edges(tbl int, id uint32, visit func(int, uint32)) {", gt)
	g.p("\tswitch tbl {")
	for _, n := range sc.tableNodes() {
		g.p("\tcase %d:", n.tbl)
		if len(n.fields) > 0 {
			hasRefs := false
			for _, fl := range n.fields {
				if fl.sh.refsNodes {
					hasRefs = true
					break
				}
			}
			if hasRefs {
				g.p("\t\tr := &g.s.%s", g.nodeIndex(n, "id"))
				for _, fl := range n.fields {
					if !fl.sh.refsNodes {
						continue
					}
					g.p("\t\t%s", g.edges(fl.sh, "r."+fl.flatName))
				}
			}
		}
	}
	g.p("\t}")
	g.p("}")
	g.p("")
	for _, n := range sc.inlineNodes() {
		if !n.refsNodes {
			continue
		}
		g.p("func (g %s) gi%d(r *%s, visit func(int, uint32)) {", gt, n.inlineID, n.flatName)
		for _, fl := range n.fields {
			if !fl.sh.refsNodes {
				continue
			}
			g.p("\t%s", g.edges(fl.sh, "r."+fl.flatName))
		}
		g.p("}")
		g.p("")
	}
	for _, sh := range sc.shapes {
		if !sh.refsNodes {
			continue
		}
		switch sh.kind {
		case kSlice, kArrayPool:
			g.p("func (g %s) g%d(x cnfrt.Span32, visit func(int, uint32)) {", gt, sh.id)
			g.p("\tif x.Len == 0 {")
			g.p("\t\treturn")
			g.p("\t}")
			g.p("\telems := g.s.%s[int(x.Off):int(x.Off)+int(x.Len)]", sh.pool.field)
			g.p("\tfor i := range elems {")
			g.p("\t\t%s", g.edges(sh.elem, "elems[i]"))
			g.p("\t}")
			g.p("}")
			g.p("")
		case kMap:
			arg, span := "cnfrt.Span32", "x"
			if sh.hashed {
				arg, span = "cnfrt.HashSpan", "x.KV"
			}
			g.p("func (g %s) g%d(x %s, visit func(int, uint32)) {", gt, sh.id, arg)
			g.p("\tif %s.Len == 0 {", span)
			g.p("\t\treturn")
			g.p("\t}")
			g.p("\tfor _, e := range g.s.%s[int(%s.Off):int(%s.Off)+int(%s.Len)] {", sh.pool.field, span, span, span)
			g.p("\t\t%s", g.edges(sh.elem, "e.V"))
			g.p("\t}")
			g.p("}")
			g.p("")
		case kIface:
			g.p("func (g %s) g%d(x cnfrt.VariantTag, visit func(int, uint32)) {", gt, sh.id)
			g.p("\tswitch x.Tag {")
			for t, im := range sh.iface.impls {
				g.p("\tcase %d:", t+1)
				g.p("\t\tvisit(%d, x.ID)", im.node.tbl)
			}
			g.p("\t}")
			g.p("}")
			g.p("")
		}
	}
}
