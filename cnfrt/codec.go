// Codec converts values of type T to and from a self-delimited byte form.
// It is the contract of custom type adapters registered with the -codec
// flag of cmd/cnfgo and of the values stored in FrozenMap, SlabMap and
// tiered.TieredMap.
//
// Append must append exactly Size(v) bytes. Decode receives a string that
// may alias an immutable snapshot blob; a decoded value may retain it.
type Codec[T any] interface {
	Size(v T) int
	Append(dst []byte, v T) []byte
	Decode(src string) (T, error)
}

// FallibleCodec is an optional extension of Codec for encoders that can fail
// (for example encoding.BinaryMarshaler). FrozenBuilder, SlabMap and
// tiered.TieredMap call AppendErr when implemented instead of Append,
// returning the error rather than panicking.
type FallibleCodec[T any] interface {
	AppendErr(dst []byte, v T) ([]byte, error)
}

// AppendValue appends the encoding of v using c, preferring AppendErr when c
// implements FallibleCodec.
func AppendValue[T any](c Codec[T], dst []byte, v T) ([]byte, error) {
	if fc, ok := c.(FallibleCodec[T]); ok {
		return fc.AppendErr(dst, v)
	}
	return c.Append(dst, v), nil
}

// SelfCodec is implemented by types that encode themselves, such as the
// Compact types generated by cmd/cnfgo. A type T implements SelfCodec if T
// has the SizeCNF and AppendCNF methods and *T has the DecodeCNF method.
type SelfCodec interface {
	SizeCNF() int
	AppendCNF(dst []byte) []byte
}

// SelfDecoder is the pointer-receiver half of SelfCodec.
type SelfDecoder interface {
	DecodeCNF(src string) error
}

// CodecProvider is implemented by types that supply a codec for themselves.
// DefaultCodec prefers it over SelfCodec: a concrete codec avoids converting
// every value to an interface. The Compact types generated by cmd/cnfgo
// implement it.
type CodecProvider[T any] interface {
	CodecCNF() Codec[T]
}

// UntrustedValidator is implemented by codecs whose Decode does not by
// itself prove that every later use of the decoded value is safe on
// arbitrary input. FrozenMap.Validate calls ValidateUntrusted instead of
// Decode for such codecs. The codecs of generated Compact types implement it
// by verifying the embedded image as cnfrt.VerifyUntrusted does.
type UntrustedValidator interface {
	ValidateUntrusted(src string) error
}

// AlignedCodec is implemented by codecs whose encodings are read in place
// and therefore should start at a multiple of AlignCNF bytes (a power of
// two of at most 8). FrozenBuilder pads the data blob so that every value
// encoded with such a codec is aligned relative to the start of the blob,
// which is itself 8-byte aligned in memory and in .cnf images. The codecs of
// generated Compact types implement it, so that View over a value stored in
// a FrozenMap casts the embedded tables without copying them.
type AlignedCodec interface {
	AlignCNF() int
}

// valueAlign returns the alignment requested by c, or 1.
func valueAlign[T any](c Codec[T]) int {
	if a, ok := c.(AlignedCodec); ok {
		if n := a.AlignCNF(); n > 1 && n <= 8 && n&(n-1) == 0 {
			return n
		}
	}
	return 1
}

// ValidateEncoded checks that src is a valid encoding for c: it calls
// ValidateUntrusted if c implements UntrustedValidator, and Decode
// otherwise.
func ValidateEncoded[T any](c Codec[T], src string) error {
	if v, ok := c.(UntrustedValidator); ok {
		return v.ValidateUntrusted(src)
	}
	_, err := c.Decode(src)
	return err
}

// copyingCodec is implemented by codecs whose decoded values never alias
// the source string.
type copyingCodec interface {
	decodesCopies() bool
}

// cloneCodec decodes from a private copy of the source, so that decoded
// values never alias the storage of the map that holds the encoding.
type cloneCodec[T any] struct{ c Codec[T] }

func (c cloneCodec[T]) Size(v T) int                  { return c.c.Size(v) }
func (c cloneCodec[T]) Append(dst []byte, v T) []byte { return c.c.Append(dst, v) }
func (c cloneCodec[T]) AppendErr(dst []byte, v T) ([]byte, error) {
	return AppendValue(c.c, dst, v)
}
func (c cloneCodec[T]) Decode(src string) (T, error) { return c.c.Decode(strings.Clone(src)) }
func (c cloneCodec[T]) ValidateUntrusted(src string) error {
	return ValidateEncoded(c.c, src)
}
func (cloneCodec[T]) decodesCopies() bool { return true }
func (c cloneCodec[T]) AlignCNF() int     { return valueAlign(c.c) }

// withClone returns a codec equivalent to c whose decoded values never alias
// the source string.
func withClone[T any](c Codec[T]) Codec[T] {
	if sc, ok := c.(stringValCodec[T]); ok {
		sc.clone = true
		return sc
	}
	if lc, ok := c.(*layoutCodec[T]); ok {
		if lc.clone {
			return lc
		}
		cp := *lc
		cp.clone = true
		return &cp
	}
	if cc, ok := c.(copyingCodec); ok && cc.decodesCopies() {
		return c
	}
	return cloneCodec[T]{c}
}

// ErrShortBuffer is returned when an encoded value is truncated.
var ErrShortBuffer = errors.New("cnfrt: truncated encoding")

var (
	timeType     = reflect.TypeFor[time.Time]()
	addrType     = reflect.TypeFor[netip.Addr]()
	prefixType   = reflect.TypeFor[netip.Prefix]()
	addrPortType = reflect.TypeFor[netip.AddrPort]()
)

// DefaultCodec returns the codec used for values of type T when none is
// configured explicitly. In order of preference it uses CodecProvider,
// SelfCodec, a lossless codec for time.Time, specialized codecs for strings,
// booleans, numbers and []byte, a layout codec for net/netip values and
// arrays/structs composed of supported types, and encoding.BinaryMarshaler.
// Floating-point values are encoded with their exact bits.
func DefaultCodec[T any]() (Codec[T], error) {
	var zero T
	if p, ok := any(zero).(CodecProvider[T]); ok {
		if c := p.CodecCNF(); c != nil {
			return c, nil
		}
	}
	if _, ok := any(zero).(SelfCodec); ok {
		if _, ok := any(&zero).(SelfDecoder); ok {
			return selfCodec[T]{}, nil
		}
	}
	t := reflect.TypeFor[T]()
	if t == timeType {
		return timeCodec[T]{}, nil
	}
	if t == addrType || t == prefixType || t == addrPortType {
		if l, err := buildLayout(t); err == nil {
			return &layoutCodec[T]{l: l}, nil
		}
	}
	switch t.Kind() {
	case reflect.String:
		return stringValCodec[T]{}, nil
	case reflect.Bool:
		return boolValCodec[T]{}, nil
	case reflect.Int8, reflect.Uint8:
		return fixed1Codec[T]{}, nil
	case reflect.Int16, reflect.Uint16:
		return fixed2Codec[T]{}, nil
	case reflect.Int32, reflect.Uint32, reflect.Float32:
		return fixed4Codec[T]{}, nil
	case reflect.Int64, reflect.Uint64, reflect.Float64:
		return fixed8Codec[T]{}, nil
	case reflect.Int, reflect.Uint:
		if t.Size() == 8 {
			return fixed8Codec[T]{}, nil
		}
		return fixed4Codec[T]{}, nil
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return bytesCodec[T]{}, nil
		}
	}
	if _, ok := any(zero).(encoding.BinaryMarshaler); ok {
		if _, ok := any(&zero).(encoding.BinaryUnmarshaler); ok {
			return binaryCodec[T]{}, nil
		}
	}
	if l, err := buildLayout(t); err == nil {
		return &layoutCodec[T]{l: l}, nil
	}
	return nil, fmt.Errorf("%w: no default codec for %v", ErrUnsupportedType, t)
}

type stringValCodec[T any] struct{ clone bool }

func (c stringValCodec[T]) decodesCopies() bool { return c.clone }
func (stringValCodec[T]) Size(v T) int          { return len(*(*string)(unsafe.Pointer(&v))) }
func (stringValCodec[T]) Append(dst []byte, v T) []byte {
	return append(dst, *(*string)(unsafe.Pointer(&v))...)
}
func (c stringValCodec[T]) Decode(src string) (T, error) {
	var v T
	if c.clone {
		src = strings.Clone(src)
	}
	*(*string)(unsafe.Pointer(&v)) = src
	return v, nil
}

type boolValCodec[T any] struct{}

func (boolValCodec[T]) decodesCopies() bool { return true }
func (boolValCodec[T]) Size(T) int          { return 1 }
func (boolValCodec[T]) Append(dst []byte, v T) []byte {
	if *(*bool)(unsafe.Pointer(&v)) {
		return append(dst, 1)
	}
	return append(dst, 0)
}
func (boolValCodec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) != 1 {
		if len(src) == 0 {
			return v, ErrShortBuffer
		}
		return v, ErrBoundsViolation
	}
	if src[0] > 1 {
		return v, ErrBoundsViolation
	}
	*(*bool)(unsafe.Pointer(&v)) = src[0] == 1
	return v, nil
}

type fixed1Codec[T any] struct{}

func (fixed1Codec[T]) decodesCopies() bool { return true }
func (fixed1Codec[T]) Size(T) int          { return 1 }
func (fixed1Codec[T]) Append(dst []byte, v T) []byte {
	return append(dst, *(*byte)(unsafe.Pointer(&v)))
}
func (fixed1Codec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) != 1 {
		if len(src) == 0 {
			return v, ErrShortBuffer
		}
		return v, ErrBoundsViolation
	}
	*(*byte)(unsafe.Pointer(&v)) = src[0]
	return v, nil
}

type fixed2Codec[T any] struct{}

func (fixed2Codec[T]) decodesCopies() bool { return true }
func (fixed2Codec[T]) Size(T) int          { return 2 }
func (fixed2Codec[T]) Append(dst []byte, v T) []byte {
	return binary.LittleEndian.AppendUint16(dst, *(*uint16)(unsafe.Pointer(&v)))
}
func (fixed2Codec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) != 2 {
		if len(src) < 2 {
			return v, ErrShortBuffer
		}
		return v, ErrBoundsViolation
	}
	*(*uint16)(unsafe.Pointer(&v)) = uint16(src[0]) | uint16(src[1])<<8
	return v, nil
}

type fixed4Codec[T any] struct{}

func (fixed4Codec[T]) decodesCopies() bool { return true }
func (fixed4Codec[T]) Size(T) int          { return 4 }
func (fixed4Codec[T]) Append(dst []byte, v T) []byte {
	return binary.LittleEndian.AppendUint32(dst, *(*uint32)(unsafe.Pointer(&v)))
}
func (fixed4Codec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) != 4 {
		if len(src) < 4 {
			return v, ErrShortBuffer
		}
		return v, ErrBoundsViolation
	}
	_ = src[3]
	*(*uint32)(unsafe.Pointer(&v)) = uint32(src[0]) | uint32(src[1])<<8 | uint32(src[2])<<16 | uint32(src[3])<<24
	return v, nil
}

type fixed8Codec[T any] struct{}

func (fixed8Codec[T]) decodesCopies() bool { return true }
func (fixed8Codec[T]) Size(T) int          { return 8 }
func (fixed8Codec[T]) Append(dst []byte, v T) []byte {
	return binary.LittleEndian.AppendUint64(dst, *(*uint64)(unsafe.Pointer(&v)))
}
func (fixed8Codec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) != 8 {
		if len(src) < 8 {
			return v, ErrShortBuffer
		}
		return v, ErrBoundsViolation
	}
	_ = src[7]
	*(*uint64)(unsafe.Pointer(&v)) = uint64(src[0]) | uint64(src[1])<<8 | uint64(src[2])<<16 | uint64(src[3])<<24 |
		uint64(src[4])<<32 | uint64(src[5])<<40 | uint64(src[6])<<48 | uint64(src[7])<<56
	return v, nil
}

// timeCodec encodes time.Time losslessly, preserving UTC, IANA location
// names (such as "Europe/Berlin") and named or anonymous fixed zones.
type timeCodec[T any] struct{}

func (timeCodec[T]) decodesCopies() bool { return true }

func classifyTimeLoc(t time.Time) (kind uint8, name string, off int) {
	loc := t.Location()
	if loc == time.UTC {
		return LocUTC, "", 0
	}
	if loc == time.Local {
		name, off = t.Zone()
		return LocFixed, name, off
	}
	name = loc.String()
	if name == "" || isFixedZone(loc) {
		_, off = t.Zone()
		return LocFixed, name, off
	}
	if _, err := ResolveLocation(name); err != nil {
		zname, zoff := t.Zone()
		return LocFixed, zname, zoff
	}
	return LocIANA, name, 0
}

func (timeCodec[T]) Size(v T) int {
	t := *(*time.Time)(unsafe.Pointer(&v))
	kind, name, _ := classifyTimeLoc(t)
	switch kind {
	case LocUTC:
		return 13
	case LocFixed:
		return 17 + len(name)
	default:
		return 13 + len(name)
	}
}

func (timeCodec[T]) AppendErr(dst []byte, v T) ([]byte, error) {
	t := *(*time.Time)(unsafe.Pointer(&v))
	kind, name, off := classifyTimeLoc(t)
	if kind == LocFixed && int(int32(off)) != off {
		return dst, ErrCapacityExceeded
	}
	dst = binary.LittleEndian.AppendUint64(dst, uint64(t.Unix()))
	dst = binary.LittleEndian.AppendUint32(dst, uint32(t.Nanosecond()))
	dst = append(dst, kind)
	switch kind {
	case LocUTC:
		return dst, nil
	case LocFixed:
		dst = binary.LittleEndian.AppendUint32(dst, uint32(int32(off)))
		return append(dst, name...), nil
	default:
		return append(dst, name...), nil
	}
}

func (c timeCodec[T]) Append(dst []byte, v T) []byte {
	out, err := c.AppendErr(dst, v)
	if err != nil {
		panic("cnfrt: timeCodec: " + err.Error())
	}
	return out
}

func (timeCodec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) < 13 {
		return v, ErrShortBuffer
	}
	sec := int64(binary.LittleEndian.Uint64(UnsafeStringBytes(src[0:8])))
	nsec := binary.LittleEndian.Uint32(UnsafeStringBytes(src[8:12]))
	if nsec >= 1e9 {
		return v, ErrBoundsViolation
	}
	t := time.Unix(sec, int64(nsec))
	switch src[12] {
	case LocUTC:
		if len(src) != 13 {
			return v, ErrBoundsViolation
		}
		t = t.UTC()
	case LocFixed:
		if len(src) < 17 {
			return v, ErrShortBuffer
		}
		off := int(int32(binary.LittleEndian.Uint32(UnsafeStringBytes(src[13:17]))))
		t = t.In(FixedLocation(src[17:], off))
	case LocIANA:
		loc, err := ResolveLocation(src[13:])
		if err != nil {
			return v, err
		}
		t = t.In(loc)
	default:
		return v, ErrBoundsViolation
	}
	*(*time.Time)(unsafe.Pointer(&v)) = t
	return v, nil
}

type selfCodec[T any] struct{}

func (selfCodec[T]) Size(v T) int { return any(v).(SelfCodec).SizeCNF() }
func (selfCodec[T]) Append(dst []byte, v T) []byte {
	return any(v).(SelfCodec).AppendCNF(dst)
}
func (selfCodec[T]) Decode(src string) (T, error) {
	var v T
	err := any(&v).(SelfDecoder).DecodeCNF(src)
	return v, err
}

type bytesCodec[T any] struct{}

func (bytesCodec[T]) decodesCopies() bool { return true }

func (bytesCodec[T]) Size(v T) int {
	return 1 + len(*(*[]byte)(unsafe.Pointer(&v)))
}

func (bytesCodec[T]) Append(dst []byte, v T) []byte {
	b := *(*[]byte)(unsafe.Pointer(&v))
	if b == nil {
		return append(dst, 0)
	}
	return append(append(dst, 1), b...)
}

func (bytesCodec[T]) Decode(src string) (T, error) {
	var v T
	if len(src) == 0 {
		return v, ErrShortBuffer
	}
	if src[0] == 1 {
		*(*[]byte)(unsafe.Pointer(&v)) = []byte(src[1:])
	} else if src[0] != 0 || len(src) != 1 {
		return v, ErrBoundsViolation
	}
	return v, nil
}

type binaryCodec[T any] struct{}

func (binaryCodec[T]) decodesCopies() bool { return true }

func (binaryCodec[T]) Size(v T) int {
	b, err := any(v).(encoding.BinaryMarshaler).MarshalBinary()
	if err != nil {
		return 0
	}
	return len(b)
}

func (binaryCodec[T]) AppendErr(dst []byte, v T) ([]byte, error) {
	if a, ok := any(v).(encoding.BinaryAppender); ok {
		return a.AppendBinary(dst)
	}
	b, err := any(v).(encoding.BinaryMarshaler).MarshalBinary()
	if err != nil {
		return dst, err
	}
	return append(dst, b...), nil
}

func (c binaryCodec[T]) Append(dst []byte, v T) []byte {
	out, err := c.AppendErr(dst, v)
	if err != nil {
		panic(fmt.Sprintf("cnfrt: MarshalBinary(%T): %v", v, err))
	}
	return out
}

func (binaryCodec[T]) Decode(src string) (T, error) {
	var v T
	err := any(&v).(encoding.BinaryUnmarshaler).UnmarshalBinary([]byte(src))
	return v, err
}

// Layout field kinds.
const (
	lkBool = iota + 1
	lkInt
	lkFloat32
	lkFloat64
	lkString
	lkAddr
	lkPrefix
	lkAddrPort
)

type layoutField struct {
	off  uintptr
	kind uint8
	size uint8
}

// layout describes how to encode a value of a type made of booleans,
// integers, floats, complex numbers, strings, net/netip values, arrays and
// structs. Padding is never encoded, so encodings of equal values are
// byte-identical.
type layout struct {
	fields    []layoutField
	fixed     int
	hasVar    bool
	rawString bool
	typ       reflect.Type
	align     uintptr // alignment of typ, which bounds merged field loads
}

func buildLayout(t reflect.Type) (*layout, error) {
	l := &layout{typ: t, align: uintptr(t.Align())}
	if err := l.add(t, 0); err != nil {
		return nil, err
	}
	l.rawString = len(l.fields) == 1 && l.fields[0].kind == lkString
	return l, nil
}

func (l *layout) add(t reflect.Type, off uintptr) error {
	switch t {
	case addrType:
		l.fields = append(l.fields, layoutField{off: off, kind: lkAddr})
		l.hasVar = true
		return nil
	case prefixType:
		l.fields = append(l.fields, layoutField{off: off, kind: lkPrefix})
		l.hasVar = true
		return nil
	case addrPortType:
		l.fields = append(l.fields, layoutField{off: off, kind: lkAddrPort})
		l.hasVar = true
		return nil
	}
	switch t.Kind() {
	case reflect.Bool:
		l.push(off, lkBool, 1)
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		l.push(off, lkInt, uint8(t.Size()))
	case reflect.Float32:
		l.push(off, lkFloat32, 4)
	case reflect.Float64:
		l.push(off, lkFloat64, 8)
	case reflect.Complex64:
		l.push(off, lkFloat32, 4)
		l.push(off+4, lkFloat32, 4)
	case reflect.Complex128:
		l.push(off, lkFloat64, 8)
		l.push(off+8, lkFloat64, 8)
	case reflect.String:
		l.fields = append(l.fields, layoutField{off: off, kind: lkString})
		l.hasVar = true
		l.fixed += 4
	case reflect.Array:
		for i := range t.Len() {
			if err := l.add(t.Elem(), off+uintptr(i)*t.Elem().Size()); err != nil {
				return err
			}
		}
	case reflect.Struct:
		for i := range t.NumField() {
			f := t.Field(i)
			if f.Name == "_" {
				continue
			}
			if err := l.add(f.Type, off+f.Offset); err != nil {
				return err
			}
		}
	default:
		return fmt.Errorf("%w: %v cannot be encoded by a layout codec", ErrUnsupportedType, t)
	}
	return nil
}

func (l *layout) push(off uintptr, kind, size uint8) {
	// Merge adjacent integer fields to speed up encoding of dense structs.
	// loadUint and storeUint access 2, 4 and 8 bytes with one typed load or
	// store, so such a merged field must be naturally aligned, both within
	// the type and in memory (the type's alignment must be at least its
	// size); other sizes are accessed byte by byte. Strict-alignment
	// platforms fault on misaligned typed accesses.
	if n := len(l.fields); n > 0 && kind == lkInt {
		last := &l.fields[n-1]
		merged := uintptr(last.size) + uintptr(size)
		aligned := true
		if merged == 2 || merged == 4 || merged == 8 {
			aligned = last.off%merged == 0 && merged <= l.align
		}
		if last.kind == lkInt && last.off+uintptr(last.size) == off && merged <= 8 && aligned && NativeLittleEndian {
			last.size += size
			l.fixed += int(size)
			return
		}
	}
	l.fields = append(l.fields, layoutField{off: off, kind: kind, size: size})
	l.fixed += int(size)
}

func addrEncodedSize(a netip.Addr) int {
	if !a.IsValid() {
		return 1
	}
	if a.Is4() {
		return 5
	}
	if z := a.Zone(); z != "" {
		return 21 + len(z)
	}
	return 17
}

func prefixEncodedSize(p netip.Prefix) int {
	a := p.Addr()
	if !a.IsValid() {
		return 1
	}
	if a.Is4() {
		return 6
	}
	return 18
}

func appendAddrCanon(dst []byte, a netip.Addr) []byte {
	if !a.IsValid() {
		return append(dst, AddrInvalid)
	}
	if a.Is4() {
		b4 := a.As4()
		dst = append(dst, AddrV4)
		return append(dst, b4[:]...)
	}
	b16 := a.As16()
	if z := a.Zone(); z != "" {
		dst = append(dst, AddrV6Zoned)
		dst = append(dst, b16[:]...)
		dst = binary.LittleEndian.AppendUint32(dst, uint32(len(z)))
		return append(dst, z...)
	}
	dst = append(dst, AddrV6)
	return append(dst, b16[:]...)
}

func decodeAddrCanon(src string, pos int, clone bool) (netip.Addr, int, error) {
	if pos >= len(src) {
		return netip.Addr{}, 0, ErrShortBuffer
	}
	switch src[pos] {
	case AddrInvalid:
		return netip.Addr{}, pos + 1, nil
	case AddrV4:
		if len(src)-pos < 5 {
			return netip.Addr{}, 0, ErrShortBuffer
		}
		var b4 [4]byte
		copy(b4[:], src[pos+1:pos+5])
		return netip.AddrFrom4(b4), pos + 5, nil
	case AddrV6:
		if len(src)-pos < 17 {
			return netip.Addr{}, 0, ErrShortBuffer
		}
		var b16 [16]byte
		copy(b16[:], src[pos+1:pos+17])
		return netip.AddrFrom16(b16), pos + 17, nil
	case AddrV6Zoned:
		if len(src)-pos < 21 {
			return netip.Addr{}, 0, ErrShortBuffer
		}
		var b16 [16]byte
		copy(b16[:], src[pos+1:pos+17])
		zlen := uint64(binary.LittleEndian.Uint32(UnsafeStringBytes(src[pos+17 : pos+21])))
		pos += 21
		if zlen == 0 || uint64(len(src)-pos) < zlen {
			if zlen == 0 {
				return netip.Addr{}, 0, ErrBoundsViolation
			}
			return netip.Addr{}, 0, ErrShortBuffer
		}
		z := src[pos : pos+int(zlen)]
		if clone {
			z = strings.Clone(z)
		}
		return netip.AddrFrom16(b16).WithZone(z), pos + int(zlen), nil
	default:
		return netip.Addr{}, 0, ErrBoundsViolation
	}
}

func appendPrefixCanon(dst []byte, p netip.Prefix) []byte {
	a := p.Addr()
	if !a.IsValid() {
		return append(dst, AddrInvalid)
	}
	bpo := uint8(p.Bits() + 1)
	if a.Is4() {
		b4 := a.As4()
		dst = append(dst, AddrV4, bpo)
		return append(dst, b4[:]...)
	}
	b16 := a.As16()
	dst = append(dst, AddrV6, bpo)
	return append(dst, b16[:]...)
}

func decodePrefixCanon(src string, pos int) (netip.Prefix, int, error) {
	if pos >= len(src) {
		return netip.Prefix{}, 0, ErrShortBuffer
	}
	switch src[pos] {
	case AddrInvalid:
		return netip.Prefix{}, pos + 1, nil
	case AddrV4:
		if len(src)-pos < 6 {
			return netip.Prefix{}, 0, ErrShortBuffer
		}
		bpo := src[pos+1]
		if bpo > 33 {
			return netip.Prefix{}, 0, ErrBoundsViolation
		}
		var b4 [4]byte
		copy(b4[:], src[pos+2:pos+6])
		return netip.PrefixFrom(netip.AddrFrom4(b4), int(bpo)-1), pos + 6, nil
	case AddrV6:
		if len(src)-pos < 18 {
			return netip.Prefix{}, 0, ErrShortBuffer
		}
		bpo := src[pos+1]
		if bpo > 129 {
			return netip.Prefix{}, 0, ErrBoundsViolation
		}
		var b16 [16]byte
		copy(b16[:], src[pos+2:pos+18])
		return netip.PrefixFrom(netip.AddrFrom16(b16), int(bpo)-1), pos + 18, nil
	default:
		return netip.Prefix{}, 0, ErrBoundsViolation
	}
}

func (l *layout) size(p unsafe.Pointer) int {
	if l.rawString {
		return len(*(*string)(p))
	}
	n := l.fixed
	if l.hasVar {
		for _, f := range l.fields {
			q := unsafe.Add(p, f.off)
			switch f.kind {
			case lkString:
				n += len(*(*string)(q))
			case lkAddr:
				n += addrEncodedSize(*(*netip.Addr)(q))
			case lkPrefix:
				n += prefixEncodedSize(*(*netip.Prefix)(q))
			case lkAddrPort:
				ap := *(*netip.AddrPort)(q)
				n += addrEncodedSize(ap.Addr()) + 2
			}
		}
	}
	return n
}

func loadUint(p unsafe.Pointer, size uint8) uint64 {
	switch size {
	case 1:
		return uint64(*(*uint8)(p))
	case 2:
		return uint64(*(*uint16)(p))
	case 4:
		return uint64(*(*uint32)(p))
	case 8:
		return *(*uint64)(p)
	}
	var v uint64
	for i := range uintptr(size) {
		v |= uint64(*(*uint8)(unsafe.Add(p, i))) << (8 * i)
	}
	return v
}

func storeUint(p unsafe.Pointer, size uint8, v uint64) {
	switch size {
	case 1:
		*(*uint8)(p) = uint8(v)
	case 2:
		*(*uint16)(p) = uint16(v)
	case 4:
		*(*uint32)(p) = uint32(v)
	case 8:
		*(*uint64)(p) = v
	default:
		for i := range uintptr(size) {
			*(*uint8)(unsafe.Add(p, i)) = uint8(v >> (8 * i))
		}
	}
}

func appendUint(dst []byte, size uint8, v uint64) []byte {
	for i := range size {
		dst = append(dst, byte(v>>(8*i)))
	}
	return dst
}

// append encodes the value at p. With canon set, floats are canonicalized
// (NaN rejected, -0.0 encoded as +0.0) for use as map keys.
func (l *layout) append(dst []byte, p unsafe.Pointer, canon bool) ([]byte, error) {
	if l.rawString {
		return append(dst, *(*string)(p)...), nil
	}
	for _, f := range l.fields {
		q := unsafe.Add(p, f.off)
		switch f.kind {
		case lkBool:
			var b byte
			if *(*bool)(q) {
				b = 1
			}
			dst = append(dst, b)
		case lkInt:
			dst = appendUint(dst, f.size, loadUint(q, f.size))
		case lkFloat32:
			bits := *(*uint32)(q)
			if canon {
				c, err := CanonFloat32(*(*float32)(q))
				if err != nil {
					return dst, err
				}
				bits = c
			}
			dst = binary.LittleEndian.AppendUint32(dst, bits)
		case lkFloat64:
			bits := *(*uint64)(q)
			if canon {
				c, err := CanonFloat64(*(*float64)(q))
				if err != nil {
					return dst, err
				}
				bits = c
			}
			dst = binary.LittleEndian.AppendUint64(dst, bits)
		case lkString:
			s := *(*string)(q)
			dst = binary.LittleEndian.AppendUint32(dst, uint32(len(s)))
			dst = append(dst, s...)
		case lkAddr:
			dst = appendAddrCanon(dst, *(*netip.Addr)(q))
		case lkPrefix:
			dst = appendPrefixCanon(dst, *(*netip.Prefix)(q))
		case lkAddrPort:
			ap := *(*netip.AddrPort)(q)
			dst = appendAddrCanon(dst, ap.Addr())
			dst = binary.LittleEndian.AppendUint16(dst, ap.Port())
		}
	}
	return dst, nil
}

// hasNaN reports whether any float field of the value at p is NaN.
func (l *layout) hasNaN(p unsafe.Pointer) bool {
	for _, f := range l.fields {
		q := unsafe.Add(p, f.off)
		switch f.kind {
		case lkFloat32:
			if v := *(*float32)(q); v != v {
				return true
			}
		case lkFloat64:
			if v := *(*float64)(q); v != v {
				return true
			}
		}
	}
	return false
}

// decode decodes src into the zeroed value at p and returns the number of
// bytes consumed. Decoded strings alias src unless clone is set.
func (l *layout) decode(src string, p unsafe.Pointer, clone bool) (int, error) {
	if l.rawString {
		if clone {
			src = strings.Clone(src)
		}
		*(*string)(p) = src
		return len(src), nil
	}
	pos := 0
	for _, f := range l.fields {
		q := unsafe.Add(p, f.off)
		switch f.kind {
		case lkBool:
			if pos >= len(src) {
				return 0, ErrShortBuffer
			}
			if src[pos] > 1 {
				return 0, ErrBoundsViolation
			}
			*(*bool)(q) = src[pos] == 1
			pos++
		case lkInt, lkFloat32, lkFloat64:
			if len(src)-pos < int(f.size) {
				return 0, ErrShortBuffer
			}
			var v uint64
			for i := range int(f.size) {
				v |= uint64(src[pos+i]) << (8 * i)
			}
			storeUint(q, f.size, v)
			pos += int(f.size)
		case lkString:
			if len(src)-pos < 4 {
				return 0, ErrShortBuffer
			}
			n := uint64(binary.LittleEndian.Uint32(UnsafeStringBytes(src[pos : pos+4])))
			pos += 4
			if uint64(len(src)-pos) < n {
				return 0, ErrShortBuffer
			}
			s := src[pos : pos+int(n)]
			if clone {
				s = strings.Clone(s)
			}
			*(*string)(q) = s
			pos += int(n)
		case lkAddr:
			a, next, err := decodeAddrCanon(src, pos, clone)
			if err != nil {
				return 0, err
			}
			*(*netip.Addr)(q) = a
			pos = next
		case lkPrefix:
			pfx, next, err := decodePrefixCanon(src, pos)
			if err != nil {
				return 0, err
			}
			*(*netip.Prefix)(q) = pfx
			pos = next
		case lkAddrPort:
			a, next, err := decodeAddrCanon(src, pos, clone)
			if err != nil {
				return 0, err
			}
			if len(src)-next < 2 {
				return 0, ErrShortBuffer
			}
			port := uint16(src[next]) | uint16(src[next+1])<<8
			*(*netip.AddrPort)(q) = netip.AddrPortFrom(a, port)
			pos = next + 2
		}
	}
	return pos, nil
}

type layoutCodec[T any] struct {
	l     *layout
	clone bool
}

func (c *layoutCodec[T]) decodesCopies() bool { return c.clone }

func (c *layoutCodec[T]) Size(v T) int { return c.l.size(unsafe.Pointer(&v)) }

func (c *layoutCodec[T]) Append(dst []byte, v T) []byte {
	out, _ := c.l.append(dst, unsafe.Pointer(&v), false)
	return out
}

func (c *layoutCodec[T]) Decode(src string) (T, error) {
	var v T
	n, err := c.l.decode(src, unsafe.Pointer(&v), c.clone)
	if err == nil && n != len(src) {
		err = ErrBoundsViolation
	}
	return v, err
}

type keyFastKind uint8

const (
	keyGeneric keyFastKind = iota
	keyString
	keyFixed8 // uint64, int64, or 64-bit int/uint
	keyFixed4 // uint32, int32, or 32-bit int/uint
)

// keyCodec encodes map keys canonically: equal keys (under Go's ==) always
// have equal encodings and NaN keys are rejected.
type keyCodec[K comparable] struct {
	l        *layout
	fast     keyFastKind
	isString bool
	hasFloat bool
	clone    bool
}

func newKeyCodec[K comparable]() (*keyCodec[K], error) {
	t := reflect.TypeFor[K]()
	l, err := buildLayout(t)
	if err != nil {
		return nil, err
	}
	kc := &keyCodec[K]{l: l, isString: t.Kind() == reflect.String}
	switch t.Kind() {
	case reflect.String:
		kc.fast = keyString
	case reflect.Uint64, reflect.Int64:
		kc.fast = keyFixed8
	case reflect.Uint32, reflect.Int32:
		kc.fast = keyFixed4
	case reflect.Int, reflect.Uint:
		if t.Size() == 8 {
			kc.fast = keyFixed8
		} else {
			kc.fast = keyFixed4
		}
	}
	for _, f := range l.fields {
		if f.kind == lkFloat32 || f.kind == lkFloat64 {
			kc.hasFloat = true
		}
	}
	return kc, nil
}

// str returns the key as a string if K's underlying type is string.
func (kc *keyCodec[K]) str(k *K) string { return *(*string)(unsafe.Pointer(k)) }

func (kc *keyCodec[K]) u64(k *K) uint64 { return *(*uint64)(unsafe.Pointer(k)) }
func (kc *keyCodec[K]) u32(k *K) uint32 { return *(*uint32)(unsafe.Pointer(k)) }

func (kc *keyCodec[K]) append(dst []byte, k *K) ([]byte, error) {
	switch kc.fast {
	case keyString:
		return append(dst, kc.str(k)...), nil
	case keyFixed8:
		return binary.LittleEndian.AppendUint64(dst, kc.u64(k)), nil
	case keyFixed4:
		return binary.LittleEndian.AppendUint32(dst, kc.u32(k)), nil
	}
	return kc.l.append(dst, unsafe.Pointer(k), true)
}

func (kc *keyCodec[K]) hasNaN(k *K) bool {
	return kc.hasFloat && kc.l.hasNaN(unsafe.Pointer(k))
}

func (kc *keyCodec[K]) decode(src string) (K, error) {
	var k K
	switch kc.fast {
	case keyString:
		if kc.clone {
			src = strings.Clone(src)
		}
		*(*string)(unsafe.Pointer(&k)) = src
		return k, nil
	case keyFixed8:
		if len(src) != 8 {
			if len(src) < 8 {
				return k, ErrShortBuffer
			}
			return k, ErrBoundsViolation
		}
		_ = src[7]
		*(*uint64)(unsafe.Pointer(&k)) = uint64(src[0]) | uint64(src[1])<<8 | uint64(src[2])<<16 | uint64(src[3])<<24 |
			uint64(src[4])<<32 | uint64(src[5])<<40 | uint64(src[6])<<48 | uint64(src[7])<<56
		return k, nil
	case keyFixed4:
		if len(src) != 4 {
			if len(src) < 4 {
				return k, ErrShortBuffer
			}
			return k, ErrBoundsViolation
		}
		_ = src[3]
		*(*uint32)(unsafe.Pointer(&k)) = uint32(src[0]) | uint32(src[1])<<8 | uint32(src[2])<<16 | uint32(src[3])<<24
		return k, nil
	}
	n, err := kc.l.decode(src, unsafe.Pointer(&k), kc.clone)
	if err == nil && n != len(src) {
		err = ErrBoundsViolation
	}
	return k, err
}

// NaNKeyFunc returns a function that reports whether a key of type K
// contains a floating-point NaN, or nil if keys of type K cannot contain
// one. A NaN is not equal to itself, so a key containing one could never be
// found again; FrozenMap, SlabMap and tiered.TieredMap reject such keys.
func NaNKeyFunc[K comparable]() func(K) bool {
	kc, err := newKeyCodec[K]()
	if err != nil || !kc.hasFloat {
		return nil
	}
	l := kc.l
	return func(k K) bool { return l.hasNaN(unsafe.Pointer(&k)) }
}

// keyBuf is a small stack buffer for encoding non-string keys.
type keyBuf [64]byte

func (kc *keyCodec[K]) encode(buf *keyBuf, k *K) (string, error) {
	switch kc.fast {
	case keyString:
		return kc.str(k), nil
	case keyFixed8:
		binary.LittleEndian.PutUint64(buf[:8], kc.u64(k))
		return UnsafeSealBytes(buf[:8]), nil
	case keyFixed4:
		binary.LittleEndian.PutUint32(buf[:4], kc.u32(k))
		return UnsafeSealBytes(buf[:4]), nil
	}
	b, err := kc.append(buf[:0], k)
	if err != nil {
		return "", err
	}
	return UnsafeSealBytes(b), nil
}
